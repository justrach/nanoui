//! Array: constructor, statics and every prototype method.

const t = @import("tests_util.zig");

test "Array" {
    try t.expectAll(&.{
        .{ .src = "new Array(3).length", .want = "3" },
        .{ .src = "new Array(1,2).join()", .want = "1,2" },
        .{ .src = "Array(2).fill(0).join()", .want = "0,0" },
        .{ .src = "try{new Array(-1)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "new Array('3').length", .want = "1" },
        .{ .src = "Array.isArray([])", .want = "true" },
        .{ .src = "Array.isArray({})", .want = "false" },
        .{ .src = "Array.isArray(new Proxy([],{}))", .want = "true" },
        .{ .src = "Array.of(1,2).join()", .want = "1,2" },
        .{ .src = "Array.from('abc').join()", .want = "a,b,c" },
        .{ .src = "Array.from({length:2,0:'x',1:'y'}).join()", .want = "x,y" },
        .{ .src = "Array.from([1,2],x=>x*2).join()", .want = "2,4" },
        .{ .src = "Array.from(new Set([1,2])).join()", .want = "1,2" },
        .{ .src = "Array.from({length:3},(_, i)=>i).join()", .want = "0,1,2" },
        .{ .src = "var a=[1]; a.push(2,3)+a.join()", .want = "31,2,3" },
        .{ .src = "var a=[1,2]; a.pop()+a.length", .want = "3" },
        .{ .src = "[].pop()", .want = "undefined" },
        .{ .src = "var a=[1,2]; a.shift()+a[0]", .want = "3" },
        .{ .src = "var a=[1]; a.unshift(2,3)+a.join()", .want = "32,3,1" },
        .{ .src = "[1,2,3,4].slice(1,3).join()", .want = "2,3" },
        .{ .src = "[1,2,3].slice(-1).join()", .want = "3" },
        .{ .src = "var a=[1,2,3,4]; a.splice(1,2).join()+'|'+a.join()", .want = "2,3|1,4" },
        .{ .src = "var a=[1,2]; a.splice(1,0,9,8); a.join()", .want = "1,9,8,2" },
        .{ .src = "var a=[1,2,3]; a.splice(1); a.join()", .want = "1" },
        .{ .src = "var a=[1,2,3]; a.splice(-1,1,7,7); a.join()", .want = "1,2,7,7" },
        .{ .src = "[1].concat(2,[3,[4]]).length", .want = "4" },
        .{ .src = "var o={length:1,0:'a',[Symbol.isConcatSpreadable]:true}; [].concat(o)[0]", .want = "a" },
        .{ .src = "[1,null,undefined,2].join('-')", .want = "1---2" },
        .{ .src = "var a=[1]; a.push(a); a.join()", .want = "1," },
        .{ .src = "[[1,2],[3]].toString()", .want = "1,2,3" },
        .{ .src = "[1,2,3].reverse().join()", .want = "3,2,1" },
        .{ .src = "[1,2,1].indexOf(1,1)", .want = "2" },
        .{ .src = "[1,2,1].lastIndexOf(1)", .want = "2" },
        .{ .src = "[NaN].indexOf(NaN)", .want = "-1" },
        .{ .src = "[NaN].includes(NaN)", .want = "true" },
        .{ .src = "[1,2].includes(3)", .want = "false" },
        .{ .src = "[1,2,3].map(x=>x*2).join()", .want = "2,4,6" },
        .{ .src = "[1,2,3].filter(x=>x%2).join()", .want = "1,3" },
        .{ .src = "[1,2,3].reduce((a,b)=>a+b)", .want = "6" },
        .{ .src = "[1,2,3].reduceRight((a,b)=>a+'-'+b)", .want = "3-2-1" },
        .{ .src = "[1,2].reduce((a,b)=>a+b,10)", .want = "13" },
        .{ .src = "try{[].reduce((a,b)=>a)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var s=0;[1,2].forEach(x=>s+=x);s", .want = "3" },
        .{ .src = "var r=[];[1,,3].forEach((x,i)=>r.push(i));r.join()", .want = "0,2" },
        .{ .src = "[1,2].every(x=>x>0)+''+[1,2].some(x=>x>1)", .want = "truetrue" },
        .{ .src = "[1,2,3].find(x=>x>1)+[1,2,3].findIndex(x=>x>1)", .want = "3" },
        .{ .src = "[1,2,3].findLast(x=>x<3)+[1,2,3].findLastIndex(x=>x<3)", .want = "3" },
        .{ .src = "[1,[2,[3,[4]]]].flat().length", .want = "3" },
        .{ .src = "[1,[2,[3,[4]]]].flat(Infinity).join()", .want = "1,2,3,4" },
        .{ .src = "[1,2].flatMap(x=>[x,x*2]).join()", .want = "1,2,2,4" },
        .{ .src = "[1,2,3].fill(0,1).join()", .want = "1,0,0" },
        .{ .src = "[1,2,3,4,5].copyWithin(0,3).join()", .want = "4,5,3,4,5" },
        .{ .src = "[1,2,3].at(-1)+[1,2,3].at(0)", .want = "4" },
        .{ .src = "[3,1,2].sort().join()", .want = "1,2,3" },
        .{ .src = "[10,9,1].sort().join()", .want = "1,10,9" },
        .{ .src = "[10,9,1].sort((a,b)=>a-b).join()", .want = "1,9,10" },
        .{ .src = "[3,undefined,1].sort().join()", .want = "1,3," },
        .{ .src = "[,3,,1].sort().length", .want = "4" },
        .{ .src = "var a=[];for(var i=0;i<100;i++)a.push({k:i%3,i:i}); a.sort((x,y)=>x.k-y.k); var ok=true; for(var i=1;i<100;i++) if(a[i-1].k==a[i].k&&a[i-1].i>a[i].i) ok=false; ok", .want = "true" },
        .{ .src = "try{[2,1].sort((a,b)=>{throw 1})}catch(e){e}", .want = "1" },
        .{ .src = "try{[].sort(1)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var a=[3,1]; var b=a.toSorted(); a[0]+''+b[0]", .want = "31" },
        .{ .src = "var a=[1,2]; a.toReversed()[0]+''+a[0]", .want = "21" },
        .{ .src = "[1,2,3].toSpliced(1,1,9).join()", .want = "1,9,3" },
        .{ .src = "[1,2].with(0,9).join()", .want = "9,2" },
        .{ .src = "try{[].with(0,1)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "[...[1,2].keys()].join()", .want = "0,1" },
        .{ .src = "[...['a'].entries()][0].join()", .want = "0,a" },
        .{ .src = "[...['a'].values()][0]", .want = "a" },
        .{ .src = "[][Symbol.iterator]===[].values", .want = "true" },
        .{ .src = "[][Symbol.iterator]().next().done", .want = "true" },
        .{ .src = "Object.prototype.toString.call([].values())", .want = "[object Array Iterator]" },
        .{ .src = "var a=[1,2]; var it=a.values(); it.next(); a.push(3); it.next();it.next().value", .want = "3" },
        .{ .src = "Array.prototype.map.call('ab',c=>c+c).join()", .want = "aa,bb" },
        .{ .src = "Array.prototype.slice.call({length:1,0:'x'})[0]", .want = "x" },
        .{ .src = "Array.prototype.push.call({length:0},1)", .want = "1" },
        .{ .src = "var o={length:2,0:1,1:2}; Array.prototype.shift.call(o); o.length+''+o[0]", .want = "12" },
        .{ .src = "var o={length:1,0:1}; Array.prototype.unshift.call(o,0); o[1]", .want = "1" },
        .{ .src = "var o={length:2,0:1,1:2}; Array.prototype.reverse.call(o); o[0]", .want = "2" },
        .{ .src = "class A extends Array{static get [Symbol.species](){return Array}}; new A(1,2).map(x=>x) instanceof A", .want = "false" },
        .{ .src = "[1,2,3].length=1", .want = "1" },
        .{ .src = "var a=new Array(5); a[4]=1; a.length+','+(0 in a)", .want = "5,false" },
        .{ .src = "var a=new Array(3); a.join('-')", .want = "--" },
        .{ .src = "var a=[]; for(var i=0;i<1000;i++)a[i]=i; a.length+a[999]", .want = "1999" },
        .{ .src = "var a=[]; for(var i=999;i>=0;i--)a[i]=i; a[0]+a[999]+a.length", .want = "1999" },
        .{ .src = "[1,2,3].toString()", .want = "1,2,3" },
        .{ .src = "[1.5,2].toLocaleString()", .want = "1.5,2" },
        .{ .src = "Array.prototype.concat.length+Array.prototype.push.length", .want = "2" },
        .{ .src = "Array.prototype.length", .want = "0" },
        .{ .src = "Array.prototype[Symbol.iterator].name", .want = "values" },
    });
}
