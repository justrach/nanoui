//! RegExp: syntax, flags, captures, lookaround, backreferences, the Symbol protocols, limits.

const t = @import("tests_util.zig");

test "RegExp" {
    try t.expectAll(&.{
        .{ .src = "/a/.test('cat')", .want = "true" },
        .{ .src = "/^a/.test('cat')", .want = "false" },
        .{ .src = "/t$/.test('cat')", .want = "true" },
        .{ .src = "/c.t/.test('c\\nt')", .want = "false" },
        .{ .src = "/c.t/s.test('c\\nt')", .want = "true" },
        .{ .src = "/^b/m.test('a\\nb')", .want = "true" },
        .{ .src = "/a$/m.test('a\\nb')", .want = "true" },
        .{ .src = "/CAT/i.test('cat')", .want = "true" },
        .{ .src = "/[a-c]+/i.exec('xABCx')[0]", .want = "ABC" },
        .{ .src = "/\\u00C9/i.test('\\u00e9')", .want = "true" },
        .{ .src = "/a{2}/.test('aa')+''+/a{3}/.test('aa')", .want = "truefalse" },
        .{ .src = "/a{1,2}/.exec('aaa')[0]", .want = "aa" },
        .{ .src = "/a{2,}/.exec('aaaa')[0]", .want = "aaaa" },
        .{ .src = "/a{1,2}?/.exec('aaa')[0]", .want = "a" },
        .{ .src = "/a*?b/.exec('aab')[0]", .want = "aab" },
        .{ .src = "/a+?/.exec('aa')[0]", .want = "a" },
        .{ .src = "/a??/.exec('a')[0]", .want = "" },
        .{ .src = "/(ab)+/.exec('ababx')[0]", .want = "abab" },
        .{ .src = "/(a)|(b)/.exec('b')[1]", .want = "undefined" },
        .{ .src = "/(a)|(b)/.exec('b')[2]", .want = "b" },
        .{ .src = "/(?:a|b)c/.exec('bc')[0]", .want = "bc" },
        .{ .src = "/(a*)*/.exec('b')[0]", .want = "" },
        .{ .src = "/(a*)+/.exec('aa')[0]", .want = "aa" },
        .{ .src = "/(z)((a+)?(b+)?(c))*/.exec('zaacbbbcac').join()", .want = "zaacbbbcac,z,ac,a,,c" },
        .{ .src = "/(?<y>\\d{4})-(?<m>\\d\\d)/.exec('2020-05').groups.m", .want = "05" },
        .{ .src = "/(?<a>x)\\k<a>/.test('xx')", .want = "true" },
        .{ .src = "/(a)\\1/.test('aa')", .want = "true" },
        .{ .src = "/(a)\\1/i.test('aA')", .want = "true" },
        .{ .src = "/\\1(a)/.exec('aa')[0]", .want = "a" },
        .{ .src = "/a(?=b)/.exec('ab')[0]", .want = "a" },
        .{ .src = "/a(?!b)/.test('ab')", .want = "false" },
        .{ .src = "/(?=(a))\\1/.exec('a')[1]", .want = "a" },
        .{ .src = "/(?<=\\$)\\d+/.exec('a$12')[0]", .want = "12" },
        .{ .src = "/(?<!\\$)\\b\\d+/.exec('$1 22')[0]", .want = "22" },
        .{ .src = "/(?<=(\\d+))x/.exec('123x')[1]", .want = "123" },
        .{ .src = "/(?<=\\1(a))b/.test('aab')", .want = "true" },
        .{ .src = "/\\bfoo\\b/.test('a foo b')", .want = "true" },
        .{ .src = "/\\Boo/.test('foo')", .want = "true" },
        .{ .src = "/[\\d]+/.exec('a12')[0]", .want = "12" },
        .{ .src = "/[^\\d]+/.exec('12ab')[0]", .want = "ab" },
        .{ .src = "/\\w+/.exec('  ab_1 ')[0]", .want = "ab_1" },
        .{ .src = "/\\W/.test('a')", .want = "false" },
        .{ .src = "/\\s/.test('\\u00a0')", .want = "true" },
        .{ .src = "/\\S+/.exec(' a ')[0]", .want = "a" },
        .{ .src = "/\\D/.test('1')", .want = "false" },
        .{ .src = "/[\\b]/.test('\\b')", .want = "true" },
        .{ .src = "/[a\\-z]+/.exec('a-z')[0]", .want = "a-z" },
        .{ .src = "/[-a]+/.exec('-a')[0]", .want = "-a" },
        .{ .src = "/[]/.test('a')", .want = "false" },
        .{ .src = "/[^]/.test('\\n')", .want = "true" },
        .{ .src = "/\\x41\\u0042\\103/.test('ABC')", .want = "true" },
        .{ .src = "/\\cA/.test('\\x01')", .want = "true" },
        .{ .src = "/\\t\\n\\r\\v\\f\\0/.test('\\t\\n\\r\\v\\f\\0')", .want = "true" },
        .{ .src = "/a{/.test('a{')", .want = "true" },
        .{ .src = "/a{1/.test('a{1')", .want = "true" },
        .{ .src = "/]/.test(']')", .want = "true" },
        .{ .src = "/\\//.test('/')", .want = "true" },
        .{ .src = "/[/]/.test('/')", .want = "true" },
        .{ .src = "/./.exec('\\u{1F600}')[0].length", .want = "1" },
        .{ .src = "/./u.exec('\\u{1F600}')[0].length", .want = "2" },
        .{ .src = "/^.$/u.test('\\u{1F600}')", .want = "true" },
        .{ .src = "/\\u{1F600}/u.test('\\u{1F600}')", .want = "true" },
        .{ .src = "/[\\u{1F600}-\\u{1F64F}]/u.test('\\u{1F601}')", .want = "true" },
        .{ .src = "/\\p{L}+/u.exec('12ab\\u00e9')[0].length", .want = "3" },
        .{ .src = "/\\p{Lu}/u.test('a')", .want = "false" },
        .{ .src = "/\\P{L}/u.test('1')", .want = "true" },
        .{ .src = "/\\p{Script=Greek}/u.test('\\u03B1')", .want = "true" },
        .{ .src = "/\\p{sc=Han}/u.test('\\u4E00')", .want = "true" },
        .{ .src = "/\\p{Emoji}/u.test('\\u{1F600}')", .want = "true" },
        .{ .src = "try{new RegExp('\\\\p{Nope}','u')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{new RegExp('(')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{new RegExp('a','gg')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{new RegExp('[b-a]')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{new RegExp('*')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{new RegExp('a{2,1}')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{new RegExp('(?<a>x)(?<a>y)')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "var r=/a/g; r.test('aa'); r.lastIndex", .want = "1" },
        .{ .src = "var r=/a/g; r.test('a'); r.test('a')+''+r.lastIndex", .want = "false0" },
        .{ .src = "var r=/a/y; r.lastIndex=1; r.test('ba')", .want = "true" },
        .{ .src = "var r=/a/y; r.test('ba')", .want = "false" },
        .{ .src = "var r=/a/; r.lastIndex=5; r.test('a')+''+r.lastIndex", .want = "true5" },
        .{ .src = "var m=/(?<n>b)/d.exec('abc'); m.indices[0].join()+m.indices.groups.n.join()", .want = "1,21,2" },
        .{ .src = "var m=/b/.exec('abc'); m.index+m.input", .want = "1abc" },
        .{ .src = "/a/.exec('b')", .want = "null" },
        .{ .src = "/a/gi.flags", .want = "gi" },
        .{ .src = "/a/dgimsuy.flags", .want = "dgimsuy" },
        .{ .src = "/a/g.global+''+/a/.global+/a/i.ignoreCase+/a/m.multiline+/a/s.dotAll+/a/u.unicode+/a/y.sticky+/a/d.hasIndices", .want = "truefalsetruetruetruetruetruetrue" },
        .{ .src = "/a\\/b/.source", .want = "a\\/b" },
        .{ .src = "new RegExp('a/b').source", .want = "a\\/b" },
        .{ .src = "new RegExp('').source", .want = "(?:)" },
        .{ .src = "new RegExp('\\n').source", .want = "\\n" },
        .{ .src = "/a/g.toString()", .want = "/a/g" },
        .{ .src = "new RegExp(/a/g).flags", .want = "g" },
        .{ .src = "new RegExp(/a/g,'i').flags", .want = "i" },
        .{ .src = "var r=/a/; RegExp(r)===r", .want = "true" },
        .{ .src = "/a/ instanceof RegExp", .want = "true" },
        .{ .src = "RegExp.prototype.toString.call({source:'x',flags:'y'})", .want = "/x/y" },
        .{ .src = "'abc'.replace(/b/,'[$&]')", .want = "a[b]c" },
        .{ .src = "'abab'.replace(/a/g,'x')", .want = "xbxb" },
        .{ .src = "'ab'.replace(/(a)(b)/,'$2$1')", .want = "ba" },
        .{ .src = "'ab'.replace(/(?<x>a)/,'[$<x>]')", .want = "[a]b" },
        .{ .src = "'a1'.replace(/\\d/,d=>d*2)", .want = "a2" },
        .{ .src = "'ab'.replace(/(a)/,(m,c,i,s)=>c+i+s)", .want = "a0abb" },
        .{ .src = "'ab'.replace(/(?<n>a)/,(...args)=>typeof args[args.length-1].n)", .want = "stringb" },
        .{ .src = "'aaa'.replace(/a*/g,'x')", .want = "xx" },
        .{ .src = "'abc'.replace(/(?:)/g,'-')", .want = "-a-b-c-" },
        .{ .src = "'\\u{1F600}'.replace(/(?:)/gu,'-').length", .want = "4" },
        .{ .src = "var r=/./g;var c=0;'abc'.replace(r,()=>{c++;return ''});c", .want = "3" },
        .{ .src = "var r=/a/g; r.lastIndex=5; 'aa'.match(r).length", .want = "2" },
        .{ .src = "RegExp.prototype[Symbol.replace].call(/a/,'a','b')", .want = "b" },
        .{ .src = "var o={[Symbol.replace](s,r){return s+r}}; 'x'.replace(o,'y')", .want = "xy" },
        .{ .src = "class R extends RegExp{exec(s){var m=super.exec(s);if(m)m[0]='Z';return m}}; 'a'.replace(new R('a'),'$&')", .want = "Z" },
        .{ .src = "[...'aXbX'.matchAll(/X/g)].length", .want = "2" },
        .{ .src = "try{'a'.matchAll(/a/)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var it='a'.matchAll(/a/g); Object.prototype.toString.call(it)", .want = "[object RegExp String Iterator]" },
        .{ .src = "var re=/(\\w+)@(\\w+)\\.com/; re.exec('me bob@site.com').slice(1).join()", .want = "bob,site" },
        .{ .src = "/^(?:[a-z0-9!#$%&'*+/=?^_`{|}~-]+)@[a-z]+\\.[a-z]{2,}$/.test('a.b@c.io')", .want = "false" },
        .{ .src = "/^[\\w.-]+@[a-z]+\\.[a-z]{2,}$/.test('a.b@c.io')", .want = "true" },
        .{ .src = "/(\\d+)-(\\d+)/.exec('10-20').slice(1).map(Number).reduce((a,b)=>a+b)", .want = "30" },
        .{ .src = "var r=''; for(var m of 'x=1;y=2'.matchAll(/(\\w)=(\\d)/g)) r+=m[1]+m[2]; r", .want = "x1y2" },
        .{ .src = "/(a+)+$/.test('aaaaaaaaaaaaaaaaaaaaaaaa')", .want = "true" },
        .{ .src = "var r; try{r=/(a+)+$/.test('a'.repeat(40)+'b')}catch(e){r=e.name} r", .want = "RangeError" },
        .{ .src = "/a|ab/.exec('ab')[0]", .want = "a" },
        .{ .src = "/((a)|b)+/.exec('ab')[2]", .want = "undefined" },
        .{ .src = "/.*/.exec('abc')[0]", .want = "abc" },
        .{ .src = "/.*c/.exec('abcd')[0]", .want = "abc" },
        .{ .src = "/a.*?c/.exec('abcbc')[0]", .want = "abc" },
        .{ .src = "/[^x]*x/.exec('abxcx')[0]", .want = "abx" },
        .{ .src = "/^\\s*$/.test('   ')", .want = "true" },
        .{ .src = "/x/.exec('\\u20ACx').index", .want = "1" },
        .{ .src = "'\\u20ACx\\u20AC'.replace(/x/,'y')==='\\u20ACy\\u20AC'", .want = "true" },
    });
}

test "more unicode properties" {
    try t.expectAll(&.{
        .{ .src = "/\\p{Bidi_Control}/u.test('\\u200f') + ',' + /\\p{Bidi_Control}/u.test('a')", .want = "true,false" },
        .{ .src = "/\\p{Cf}/u.test('\\u200b') + ',' + /\\p{Default_Ignorable_Code_Point}/u.test('\\ufeff')", .want = "true,true" },
        .{ .src = "/\\p{Script=Tagalog}/u.test('a')", .want = "false" },
        .{ .src = "/\\p{Pd}/u.test('-') + ',' + /\\p{Hex_Digit}+/u.exec('xfa')[0]", .want = "true,fa" },
    });
}
