test "control flow" {
    try t.expectAll(&.{
        .{ .src = "var s=0; for(var i=0;i<5;i++){ if(i==1)continue; if(i==3)break; s+=i } s", .want = "2" },
        .{ .src = "var i=0; while(i<3) i++; i", .want = "3" },
        .{ .src = "var i=0; do { i++ } while(i<3); i", .want = "3" },
        .{ .src = "a: for(var i=0;i<3;i++){ for(var j=0;j<3;j++){ if(j==1) continue a; if(i==2) break a; } } i", .want = "2" },
        .{ .src = "var r=''; b: { r+='x'; break b; r+='y'; } r", .want = "x" },
        .{ .src = "function f(x){switch(x){case 1:return 'a';case 2:case 3:return 'b';default:return 'c'}} f(1)+f(3)+f(9)", .want = "abc" },
        .{ .src = "var r='';switch(2){case 1:r+='1';case 2:r+='2';case 3:r+='3';break;case 4:r+='4'} r", .want = "23" },
        .{ .src = "var r='';switch(9){default:r+='d';case 1:r+='1'} r", .want = "d1" },
        .{ .src = "switch(1){case 1:let x=1; x}", .want = "1" },
        .{ .src = "var r=''; for(var k in {a:1,b:2}) r+=k; r", .want = "ab" },
        .{ .src = "var r=''; for(var k in [5,6]) r+=k; r", .want = "01" },
        .{ .src = "var o=Object.create({p:1}); o.q=2; var r=[]; for(var k in o) r.push(k); r.join()", .want = "q,p" },
        .{ .src = "var o={a:1,b:2,c:3}; var r=''; for(var k in o){ r+=k; delete o.b } r", .want = "ac" },
        .{ .src = "var o={b:1,2:1,a:1,1:1}; Object.keys(o).join()", .want = "1,2,b,a" },
        .{ .src = "var r=0; for(var v of [1,2,3]) r+=v; r", .want = "6" },
        .{ .src = "var r=''; for(var c of 'a\\u{1F600}') r+=c.length; r", .want = "12" },
        .{ .src = "var r=0; for(const [a,b] of [[1,2],[3,4]]) r+=a*b; r", .want = "14" },
        .{ .src = "var closed=false; var it={[Symbol.iterator](){return {next(){return {value:1,done:false}},return(){closed=true;return {}}}}}; for(var v of it) break; closed", .want = "true" },
        .{ .src = "var closed=false; var it={[Symbol.iterator](){return {next(){return {value:1,done:false}},return(){closed=true;return {}}}}}; try{for(var v of it) throw 1}catch(e){} closed", .want = "true" },
        .{ .src = "var closed=false; var it={[Symbol.iterator](){return {next(){return {value:1,done:false}},return(){closed=true;return {}}}}}; (function(){for(var v of it) return v})(); closed", .want = "true" },
        .{ .src = "var closed=false; var it={[Symbol.iterator](){return {next(){throw 1},return(){closed=true;return {}}}}}; try{for(var v of it);}catch(e){} closed", .want = "false" },
        .{ .src = "try { throw 1 } catch(e){ e+1 }", .want = "2" },
        .{ .src = "try { throw 1 } catch { 7 }", .want = "7" },
        .{ .src = "function f(){ try { return 1 } finally { g=2 } } var g; f()+g", .want = "3" },
        .{ .src = "function f(){ try { return 1 } finally { return 2 } } f()", .want = "2" },
        .{ .src = "function f(){ try { throw 1 } catch(e){ return e+1 } finally { h=9 } } var h; f()+h", .want = "11" },
        .{ .src = "function f(){ for(var i=0;i<3;i++){ try { continue } finally { r+=i } } } var r=''; f(); r", .want = "012" },
        .{ .src = "function f(){ l: for(;;){ try { break l } finally { r='z' } } } var r; f(); r", .want = "z" },
        .{ .src = "function f(){ try { try { throw 1 } finally { a='x' } } catch(e){ return a+e } } var a; f()", .want = "x1" },
        .{ .src = "function f(){ try { return 'a' } finally { try { throw 1 } catch(e){} } } f()", .want = "a" },
        .{ .src = "function f(){ for(;;){ try { return 1 } finally { break } } return 2 } f()", .want = "2" },
        .{ .src = "try { null.x } catch(e){ e.message }", .want = "Cannot read properties of null (reading 'x')" },
        .{ .src = "try { undefined.x=1 } catch(e){ e.name }", .want = "TypeError" },
        .{ .src = "try { var f; f() } catch(e){ e.message }", .want = "f is not a function" },
        .{ .src = "try { var o={}; o.m() } catch(e){ e.message }", .want = "o.m is not a function" },
        .{ .src = "try { nope } catch(e){ e.message }", .want = "nope is not defined" },
        .{ .src = "function f(){ f() } try { f() } catch(e){ e.name+e.message }", .want = "RangeErrorMaximum call stack size exceeded" },
    });
}

