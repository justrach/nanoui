test "variables, scope, TDZ" {
    try t.expectAll(&.{
        .{ .src = "let a=1; { let a=2; } a", .want = "1" },
        .{ .src = "var a=1; { var a=2; } a", .want = "2" },
        .{ .src = "const c=1; c", .want = "1" },
        .{ .src = "try { c; const c=1; } catch(e){ e.name }", .want = "ReferenceError" },
        .{ .src = "try { x; let x; } catch(e){ e.message }", .want = "Cannot access 'x' before initialization" },
        .{ .src = "try { const c=1; c=2; } catch(e){ e.name }", .want = "TypeError" },
        .{ .src = "function f(){ return g(); function g(){ return x; } let x=1; } try { f() } catch(e){ e.name }", .want = "ReferenceError" },
        .{ .src = "typeof hoisted; function hoisted(){}; typeof hoisted", .want = "function" },
        .{ .src = "var r=typeof v; var v=1; r", .want = "undefined" },
        .{ .src = "function f(){ return a; var a=1; } f()", .want = "undefined" },
        .{ .src = "var fs=[]; for(let i=0;i<3;i++) fs.push(()=>i); fs.map(f=>f()).join()", .want = "0,1,2" },
        .{ .src = "var fs=[]; for(var i=0;i<3;i++) fs.push(()=>i); fs.map(f=>f()).join()", .want = "3,3,3" },
