    try t.expectAll(&.{
        .{ .src = "class A{constructor(x){this.x=x} get d(){return this.x*2} static s(){return 1}} new A(2).d+A.s()", .want = "5" },
        .{ .src = "class A{f=1;g=this.f+1} new A().g", .want = "2" },
        .{ .src = "class A{static f=1;static g=this.f+1} A.g", .want = "2" },
        .{ .src = "class A{['x'+1]=2} new A().x1", .want = "2" },
        .{ .src = "class A{f} Object.keys(new A()).join()", .want = "f" },
        .{ .src = "class A{f=()=>this} var a=new A(); a.f()===a", .want = "true" },
        .{ .src = "class A{#p=1;get(){return this.#p}set(v){this.#p=v}} var a=new A(); a.set(5); a.get()", .want = "5" },
