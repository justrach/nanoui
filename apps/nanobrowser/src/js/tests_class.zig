        .{ .src = "class A{#m(){return 1}n(){return this.#m()}} new A().n()", .want = "1" },
        .{ .src = "class A{get #g(){return this.v}set #g(x){this.v=x+1}t(){this.#g=1;return this.#g}} new A().t()", .want = "2" },
        .{ .src = "class A{static #s=2;static g(){return A.#s}} A.g()", .want = "2" },
        .{ .src = "class A{static #m(){return 3}static g(){return A.#m()}} A.g()", .want = "3" },
        .{ .src = "class A{#p;static t(o){return o.#p}} try{A.t({})}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "class A{#m(){}t(){this.#m=1}} try{new A().t()}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "try{eval('class A{m(){this.#x}}')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "class A{#x=1;m(){return ()=>this.#x}} new A().m()()", .want = "1" },
        .{ .src = "class A{#x=1;i(){return class{g(o){return o.#x}}}} var a=new A(); new (a.i())().g(a)", .want = "1" },
        .{ .src = "class A{#x=1;n(){this.#x++;this.#x+=2;return this.#x}} new A().n()", .want = "4" },
        .{ .src = "var c=0; class A{static{c=1}static x=c+1;static{c=this.x}} c", .want = "2" },
        .{ .src = "class A{static{var v=1;this.w=v}} A.w", .want = "1" },
        .{ .src = "class A{m(){return 1}} class B extends A{m(){return super.m()+1}} new B().m()", .want = "2" },
        .{ .src = "class A{constructor(){this.a=1}} class B extends A{constructor(){super();this.b=2}} var b=new B(); b.a+b.b", .want = "3" },
        .{ .src = "class A{constructor(x){this.x=x}} class B extends A{} new B(5).x", .want = "5" },
        .{ .src = "class A{} class B extends A{f=1} new B().f", .want = "1" },
        .{ .src = "class A{constructor(){this.seen=this.f}} class B extends A{f=1} new B().seen", .want = "undefined" },
