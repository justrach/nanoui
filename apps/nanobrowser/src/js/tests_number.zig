        .{ .src = "-10n/3n", .want = "-3" },
        .{ .src = "10n%3n", .want = "1" },
        .{ .src = "-10n%3n", .want = "-1" },
        .{ .src = "try{1n/0n}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "try{1n+1}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "-(5n)", .want = "-5" },
        .{ .src = "5n&3n", .want = "1" },
        .{ .src = "5n|3n", .want = "7" },
        .{ .src = "5n^3n", .want = "6" },
        .{ .src = "~5n", .want = "-6" },
        .{ .src = "-5n&3n", .want = "3" },
        .{ .src = "-5n|3n", .want = "-5" },
        .{ .src = "1n<<70n", .want = "1180591620717411303424" },
        .{ .src = "-9n>>1n", .want = "-5" },
        .{ .src = "try{1n>>>1n}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "1n<2", .want = "true" },
        .{ .src = "2>1n", .want = "true" },
        .{ .src = "1n==1", .want = "true" },
        .{ .src = "1n===1", .want = "false" },
        .{ .src = "1n=='1'", .want = "true" },
        .{ .src = "2n>'1'", .want = "true" },
        .{ .src = "0n?1:2", .want = "2" },
