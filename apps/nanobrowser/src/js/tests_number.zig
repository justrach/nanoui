        .{ .src = "(255).toString(2)", .want = "11111111" },
        .{ .src = "(-255).toString(36)", .want = "-73" },
        .{ .src = "(0.5).toString(2)", .want = "0.1" },
        .{ .src = "(0.1).toString(3).slice(0,8)", .want = "0.002200" },
        .{ .src = "try{(1).toString(1)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "(1.005).toFixed(2)", .want = "1.00" },
        .{ .src = "(1.5).toFixed(0)", .want = "2" },
        .{ .src = "(2.5).toFixed(0)", .want = "3" },
        .{ .src = "(0).toFixed(2)", .want = "0.00" },
        .{ .src = "(-1.5).toFixed(1)", .want = "-1.5" },
        .{ .src = "(1e21).toFixed(2)", .want = "1e+21" },
        .{ .src = "(1234.5678).toFixed(2)", .want = "1234.57" },
        .{ .src = "try{(1).toFixed(101)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "(1234).toExponential(2)", .want = "1.23e+3" },
        .{ .src = "(0.00015).toExponential()", .want = "1.5e-4" },
        .{ .src = "(1234.5).toPrecision(2)", .want = "1.2e+3" },
        .{ .src = "(1234.5).toPrecision(6)", .want = "1234.50" },
        .{ .src = "(0.00001).toPrecision(1)", .want = "0.00001" },
        .{ .src = "(1).toPrecision()", .want = "1" },
        .{ .src = "Number.isInteger(1)+''+Number.isInteger(1.5)+Number.isSafeInteger(2**53)", .want = "truefalsefalse" },
        .{ .src = "Number.isNaN('a')+''+isNaN('a')", .want = "falsetrue" },
        .{ .src = "Number.isFinite('1')+''+isFinite('1')", .want = "falsetrue" },
        .{ .src = "Number.MAX_SAFE_INTEGER", .want = "9007199254740991" },
        .{ .src = "Number.MAX_VALUE", .want = "1.7976931348623157e+308" },
        .{ .src = "Number.MIN_VALUE", .want = "5e-324" },
        .{ .src = "Number.EPSILON", .want = "2.220446049250313e-16" },
        .{ .src = "parseInt('42px')+parseInt('0x10')+parseInt('101',2)", .want = "63" },
        .{ .src = "parseInt('z',36)", .want = "35" },
        .{ .src = "parseInt('')", .want = "NaN" },
        .{ .src = "parseInt('  -7')", .want = "-7" },
        .{ .src = "parseInt(null)", .want = "NaN" },
        .{ .src = "parseInt('12',1)", .want = "NaN" },
