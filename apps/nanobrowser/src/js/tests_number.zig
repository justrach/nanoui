test "Intl stubs" {
    try t.expectAll(&.{
        .{ .src = "new Intl.NumberFormat('en-US').format(1234567.891)", .want = "1,234,567.891" },
        .{ .src = "new Intl.NumberFormat('en-US',{style:'currency',currency:'USD'}).format(1234.5)", .want = "$1,234.50" },
        .{ .src = "new Intl.NumberFormat('en-US',{style:'percent'}).format(0.25)", .want = "25%" },
        .{ .src = "new Intl.NumberFormat('en-US',{maximumFractionDigits:1}).format(1.26)", .want = "1.3" },
        .{ .src = "(1234.5).toLocaleString()", .want = "1,234.5" },
        .{ .src = "(1234.5).toLocaleString('en-US',{minimumFractionDigits:2})", .want = "1,234.50" },
        .{ .src = "var f=new Intl.NumberFormat().format; f(1000)", .want = "1,000" },
        .{ .src = "new Intl.DateTimeFormat('en-US').format(new Date(0))", .want = "1/1/1970" },
        .{ .src = "new Intl.DateTimeFormat().resolvedOptions().locale", .want = "en-US" },
        .{ .src = "['b','a'].sort(new Intl.Collator().compare).join('')", .want = "ab" },
        .{ .src = "new Intl.PluralRules('en').select(1)", .want = "one" },
        .{ .src = "new Intl.ListFormat('en').format(['a','b','c'])", .want = "a, b, and c" },
        .{ .src = "new Intl.RelativeTimeFormat('en').format(-2,'day')", .want = "2 days ago" },
        .{ .src = "typeof Intl", .want = "object" },
        .{ .src = "new Date(0).toLocaleDateString()", .want = "1/1/1970" },
        .{ .src = "new Date(0).toLocaleTimeString()", .want = "12:00:00 AM" },
        .{ .src = "new Date(0).toLocaleString()", .want = "1/1/1970, 12:00:00 AM" },
    });
}
