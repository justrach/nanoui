        .{ .src = "var k='z',o={[k]:function(){}}; o.z.name", .want = "z" },
        .{ .src = "var s=Symbol('d'),o={[s]:function(){}}; o[s].name", .want = "[d]" },
        .{ .src = "var f=function g(){return typeof g}; f()", .want = "function" },
        .{ .src = "var f=function g(){g=1;return typeof g}; f()", .want = "function" },
        .{ .src = "var f=function g(){'use strict';try{g=1}catch(e){return e.name}}; f()", .want = "TypeError" },
        .{ .src = "function f(){return arguments.length}; f(1,2,3)", .want = "3" },
        .{ .src = "function f(){return arguments[1]}; f(1,2,3)", .want = "2" },
        .{ .src = "function f(){return Array.prototype.slice.call(arguments,1).join()}; f(1,2,3)", .want = "2,3" },
        .{ .src = "function f(){return [...arguments].length}; f(1,2)", .want = "2" },
        .{ .src = "function f(){return Object.prototype.toString.call(arguments)}; f()", .want = "[object Arguments]" },
        .{ .src = "function f(){var g=()=>arguments[0]; return g(9)}; f(1)", .want = "1" },
        .{ .src = "function f(){return (()=>this.v)()}; f.call({v:3})", .want = "3" },
        .{ .src = "function f(){return (()=>new.target)()}; typeof new f()", .want = "function" },
        .{ .src = "function F(){return new.target===F}; new F() instanceof F", .want = "true" },
        .{ .src = "function F(){return {a:1}}; new F().a", .want = "1" },
        .{ .src = "function F(){return 1}; typeof new F()", .want = "object" },
        .{ .src = "function F(){}; F.prototype.m=function(){return 1}; new F().m()", .want = "1" },
        .{ .src = "function F(){}; new F().constructor===F", .want = "true" },
        .{ .src = "function mk(){var c=0;return function(){return ++c}}; var a=mk(),b=mk(); a();a();b()+a()", .want = "4" },
        .{ .src = "var f=function(){return this}.bind(7); typeof f()", .want = "object" },
        .{ .src = "function f(a,b){return a+b}; f.bind(null,1)(2)", .want = "3" },
        .{ .src = "function f(a,b){}; f.bind(null,1).length", .want = "1" },
        .{ .src = "function f(){}; f.bind().name", .want = "bound f" },
        .{ .src = "function F(a){this.a=a}; var G=F.bind(null,5); new G().a", .want = "5" },
        .{ .src = "Math.max.apply(null,[1,3,2])", .want = "3" },
        .{ .src = "function f(){return this.x}; f.call({x:2})", .want = "2" },
        .{ .src = "function f(){return 1}; f.toString()", .want = "function f(){return 1}" },
        .{ .src = "(a=>a+1).toString()", .want = "a=>a+1" },
        .{ .src = "class A{m(){}}; A.toString()", .want = "class A{m(){}}" },
        .{ .src = "class A{static m(a){return a}}; A.m.toString()", .want = "m(a){return a}" },
        .{ .src = "var o={get x(){return 1}}; Object.getOwnPropertyDescriptor(o,'x').get.toString()", .want = "get x(){return 1}" },
        .{ .src = "Math.max.toString()", .want = "function max() { [native code] }" },
        .{ .src = "new Function('a','b','return a+b')(1,2)", .want = "3" },
        .{ .src = "new Function('return this')()===globalThis", .want = "true" },
        .{ .src = "Function('return 1').toString().indexOf('anonymous')>0", .want = "true" },
        .{ .src = "eval('1+1')", .want = "2" },
        .{ .src = "(0,eval)('var ev=3'); ev", .want = "3" },
        .{ .src = "eval(5)", .want = "5" },
        .{ .src = "eval('let q=1; q+1')", .want = "2" },
        .{ .src = "try{eval('{')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{new Function('(')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "var r; try { eval('\"use strict\";with(a){}') } catch(e){ r=e.name } r", .want = "SyntaxError" },
        .{ .src = "var o={a:1}; with(o){a}", .want = "1" },
        .{ .src = "var o={a:1},a=9; with(o){a=2} o.a+a", .want = "11" },
        .{ .src = "var o={},a=9; with(o){a=2} a", .want = "2" },
        .{ .src = "var o={},z; with(o){z=2} z", .want = "2" },
        .{ .src = "var o={a:1}; with(o){a++;a+=1} o.a", .want = "3" },
        .{ .src = "var o={f(){return this===o}}; with(o){f()}", .want = "true" },
        .{ .src = "function g(){return this===globalThis}; with({}){g()}", .want = "true" },
        .{ .src = "var o={a:1}; with(o){typeof a}", .want = "number" },
        .{ .src = "var o={a:1}; with(o){delete a} 'a' in o", .want = "false" },
        .{ .src = "var o={a:1}; with(o){var f=function(){return a}} o.a=2; f()", .want = "2" },
        .{ .src = "with({a:1}){with({b:2}){a+b}}", .want = "3" },
        .{ .src = "var o={[Symbol.unscopables]:{a:true},a:1},a=5; with(o){a}", .want = "5" },
        .{ .src = "with([1,2]){length+(typeof values)}", .want = "2undefined" },
        .{ .src = "with(Math){max(1,2)+floor(PI)}", .want = "5" },
        .{ .src = "var r=[]; for(var i=0;i<2;i++){with({i:i*10}){r.push(i);continue}} r.join()", .want = "0,10" },
        .{ .src = "function f(){with({v:1}){return v}} f()", .want = "1" },
        .{ .src = "function f(d){with(d){return `${name}:${x+1}`}} f({name:'n',x:1})", .want = "n:2" },
        .{ .src = "try{with(null){}}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "new Function('obj','with(obj){return a+b}')({a:1,b:2})", .want = "3" },
        .{ .src = "(function(){ var f=function(){ return f }; return f()===f })()", .want = "true" },
        .{ .src = "(x=>y=>z=>x+y+z)(1)(2)(3)", .want = "6" },
        .{ .src = "(async=>async)(1)", .want = "1" },
        .{ .src = "((a,{b},[c],...d)=>a+b+c+d[0])(1,{b:2},[3],4)", .want = "10" },
        .{ .src = "((a=1,{b=2}={})=>a+b)()", .want = "3" },
        .{ .src = "var o={f(){return super.toString===Object.prototype.toString}}; o.f()", .want = "true" },
    });
}

test "destructuring and spread" {
    try t.expectAll(&.{
        .{ .src = "var [a,b]=[1,2]; a+b", .want = "3" },
        .{ .src = "var [a,,b]=[1,2,3]; b", .want = "3" },
        .{ .src = "var [a=5]=[]; a", .want = "5" },
        .{ .src = "var [a,...r]=[1,2,3]; r.join()", .want = "2,3" },
        .{ .src = "var {a,b:c}={a:1,b:2}; a+c", .want = "3" },
        .{ .src = "var {a=9,b:{c}={c:2}}={}; a+c", .want = "11" },
        .{ .src = "var {a,...r}={a:1,b:2,c:3}; Object.keys(r).join()", .want = "b,c" },
        .{ .src = "var k='x',{[k]:v,...r}={x:1,y:2}; v+Object.keys(r).join()", .want = "1y" },
        .{ .src = "var a,b; [a,b]=[1,2]; [a,b]=[b,a]; a", .want = "2" },
        .{ .src = "var a,b; ({a,b}={a:1,b:2}); a+b", .want = "3" },
        .{ .src = "var o={}; [o.x,o['y']]=[1,2]; o.x+o.y", .want = "3" },
        .{ .src = "var o={}; ({a:o.p}={a:5}); o.p", .want = "5" },
        .{ .src = "var r=[a,b]=[1,2]; var a,b; r.length", .want = "2" },
        .{ .src = "var [a,[b,[c]]]=[1,[2,[3]]]; c", .want = "3" },
        .{ .src = "try { var {a}=null } catch(e){ e.name }", .want = "TypeError" },
        .{ .src = "try { var [a]=1 } catch(e){ e.message }", .want = "number is not iterable" },
        .{ .src = "var [x]='hi'; x", .want = "h" },
        .{ .src = "var c=0,it={[Symbol.iterator](){return {next(){return{value:1,done:false}},return(){c++;return{}}}}}; var [a]=it; c", .want = "1" },
        .{ .src = "var c=0,it={[Symbol.iterator](){return {next(){return{done:true}},return(){c++;return{}}}}}; var [a]=it; c", .want = "0" },
        .{ .src = "function f({a,b}={a:1,b:2}){return a+b}; f()", .want = "3" },
        .{ .src = "function f([a,b]){return a+b}; f([1,2])", .want = "3" },
        .{ .src = "function f(x){var y=x;function g(){return y+x}return g()}; f(1)", .want = "2" },
        .{ .src = "[...[1,2],...'ab',3].join()", .want = "1,2,a,b,3" },
        .{ .src = "Math.max(...[1,2],3)", .want = "3" },
        .{ .src = "function F(a,b){this.s=a+b}; new F(...[1,2]).s", .want = "3" },
        .{ .src = "var o={a:1,...{b:2},...null,...'x'}; Object.keys(o).join()", .want = "0,a,b" },
        .{ .src = "[,1,,2].length", .want = "4" },
        .{ .src = "0 in [,1]", .want = "false" },
        .{ .src = "[1,,].length", .want = "2" },
        .{ .src = "[...new Set([1,1,2])].length", .want = "2" },
        .{ .src = "var m=new Map([[1,2]]); var [[k,v]]=m; k+v", .want = "3" },
        .{ .src = "for(var {a} of [{a:1}]) ; a", .want = "1" },
    });
}

