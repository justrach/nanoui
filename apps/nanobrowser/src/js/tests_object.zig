//! Object statics and prototype, Reflect-independent property semantics, Symbol, Error.

const t = @import("tests_util.zig");

test "Object" {
    try t.expectAll(&.{
        .{ .src = "Object.keys({a:1,b:2}).join()", .want = "a,b" },
        .{ .src = "Object.values({a:1,b:2}).join()", .want = "1,2" },
        .{ .src = "Object.entries({a:1})[0].join()", .want = "a,1" },
        .{ .src = "Object.assign({a:1},{b:2},null,{c:3}).c", .want = "3" },
        .{ .src = "var o=Object.assign({},{get x(){return 5}}); Object.getOwnPropertyDescriptor(o,'x').value", .want = "5" },
        .{ .src = "Object.fromEntries([['a',1],['b',2]]).b", .want = "2" },
        .{ .src = "Object.fromEntries(new Map([['a',1]])).a", .want = "1" },
        .{ .src = "var d=Object.getOwnPropertyDescriptor({a:1},'a'); [d.value,d.writable,d.enumerable,d.configurable].join()", .want = "1,true,true,true" },
        .{ .src = "var d=Object.getOwnPropertyDescriptors({a:1,get b(){return 1}}); typeof d.b.get+d.a.value", .want = "function1" },
        .{ .src = "var o={}; Object.defineProperties(o,{a:{value:1,enumerable:true},b:{get(){return 2}}}); o.a+o.b+Object.keys(o).join()", .want = "3a" },
        .{ .src = "var o={}; Object.defineProperty(o,'a',{value:1}); var d=Object.getOwnPropertyDescriptor(o,'a'); d.writable+''+d.enumerable+d.configurable", .want = "falsefalsefalse" },
        .{ .src = "var o={}; Object.defineProperty(o,'a',{value:1}); try{Object.defineProperty(o,'a',{value:2})}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var o={}; Object.defineProperty(o,'a',{value:1}); Object.defineProperty(o,'a',{value:1}); o.a", .want = "1" },
        .{ .src = "var o={a:1}; Object.defineProperty(o,'a',{enumerable:false}); Object.keys(o).length+o.a", .want = "1" },
        .{ .src = "var o={a:1}; Object.defineProperty(o,'a',{get(){return 9}}); o.a", .want = "9" },
        .{ .src = "var a=[1,2]; Object.defineProperty(a,0,{value:5,enumerable:false}); a[0]+Object.keys(a).join()", .want = "51" },
        .{ .src = "var a=[1,2]; Object.defineProperty(a,0,{get(){return 7}}); a[0]+a[1]", .want = "9" },
        .{ .src = "var a=[]; Object.defineProperty(a,'length',{value:3}); a.length", .want = "3" },
        .{ .src = "var a=[1]; Object.defineProperty(a,'length',{writable:false}); a[1]=2; a.length", .want = "1" },
        .{ .src = "try{Object.defineProperty(1,'a',{})}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "try{Object.defineProperty({},'a',{get(){},value:1})}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "Object.isFrozen(Object.freeze({}))", .want = "true" },
        .{ .src = "Object.isFrozen({})", .want = "false" },
        .{ .src = "Object.isSealed(Object.seal({a:1}))", .want = "true" },
        .{ .src = "var o=Object.seal({a:1}); o.a=2; o.b=3; delete o.a; o.a+''+o.b", .want = "2undefined" },
        .{ .src = "var o=Object.preventExtensions({a:1}); o.b=1; Object.isExtensible(o)+''+o.b", .want = "falseundefined" },
        .{ .src = "Object.isFrozen(1)", .want = "true" },
        .{ .src = "Object.freeze(1)", .want = "1" },
        .{ .src = "Object.is(NaN,NaN)+''+Object.is(0,-0)", .want = "truefalse" },
        .{ .src = "Object.getPrototypeOf([])===Array.prototype", .want = "true" },
        .{ .src = "Object.getPrototypeOf(1)===Number.prototype", .want = "true" },
        .{ .src = "try{Object.getPrototypeOf(null)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var p={}; Object.getPrototypeOf(Object.setPrototypeOf({},p))===p", .want = "true" },
        .{ .src = "Object.getOwnPropertyNames({a:1,[Symbol()]:2}).join()", .want = "a" },
        .{ .src = "Object.getOwnPropertySymbols({a:1,[Symbol.iterator]:2})[0]===Symbol.iterator", .want = "true" },
        .{ .src = "Object.hasOwn({a:1},'a')", .want = "true" },
        .{ .src = "Object.groupBy([1,2,3],x=>x%2?'o':'e').o.join()", .want = "1,3" },
