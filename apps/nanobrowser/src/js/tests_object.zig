        .{ .src = "Object.getOwnPropertyDescriptor(Object.prototype,'__proto__').get.call(1)===Number.prototype", .want = "true" },
    });
}

test "Symbol" {
    try t.expectAll(&.{
        .{ .src = "Symbol('a').toString()", .want = "Symbol(a)" },
        .{ .src = "Symbol('a').description", .want = "a" },
        .{ .src = "Symbol().description", .want = "undefined" },
        .{ .src = "String(Symbol('b'))", .want = "Symbol(b)" },
        .{ .src = "Symbol.for('x')===Symbol.for('x')", .want = "true" },
        .{ .src = "Symbol.keyFor(Symbol.for('x'))", .want = "x" },
        .{ .src = "Symbol.keyFor(Symbol('x'))", .want = "undefined" },
        .{ .src = "try{new Symbol}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "typeof Symbol.iterator", .want = "symbol" },
        .{ .src = "typeof Symbol.asyncIterator+typeof Symbol.toPrimitive+typeof Symbol.hasInstance+typeof Symbol.toStringTag", .want = "symbolsymbolsymbolsymbol" },
        .{ .src = "var s=Symbol(),o={[s]:1}; o[s]+Object.keys(o).length", .want = "1" },
        .{ .src = "var o={[Symbol.iterator]:function*(){yield 1}}; [...o][0]", .want = "1" },
        .{ .src = "Object(Symbol('q')).toString()", .want = "Symbol(q)" },
        .{ .src = "var s=Symbol(); Object(s)==s", .want = "true" },
        .{ .src = "try{`${Symbol()}`}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "class E{static [Symbol.hasInstance](v){return v==1}}; 1 instanceof E", .want = "true" },
    });
}

test "Error" {
    try t.expectAll(&.{
        .{ .src = "new Error('m').message", .want = "m" },
        .{ .src = "new Error('m').name", .want = "Error" },
        .{ .src = "new Error('m').toString()", .want = "Error: m" },
        .{ .src = "new TypeError('t').toString()", .want = "TypeError: t" },
        .{ .src = "Error('x') instanceof Error", .want = "true" },
        .{ .src = "new RangeError('r') instanceof Error", .want = "true" },
        .{ .src = "new SyntaxError('s').name+new ReferenceError('s').name+new EvalError('s').name+new URIError('s').name", .want = "SyntaxErrorReferenceErrorEvalErrorURIError" },
        .{ .src = "new Error('m',{cause:5}).cause", .want = "5" },
        .{ .src = "'cause' in new Error('m')", .want = "false" },
        .{ .src = "typeof new Error('m').stack", .want = "string" },
        .{ .src = "new Error('m').stack.split('\\n')[0]", .want = "Error: m" },
        .{ .src = "function foo(){return new Error('x').stack}; foo().indexOf('at foo (test.js:1:')>0", .want = "true" },
        .{ .src = "Object.keys(new Error('x')).length", .want = "0" },
        .{ .src = "var o={name:'N',message:'M'}; Error.prototype.toString.call(o)", .want = "N: M" },
        .{ .src = "var o={}; Error.captureStackTrace(o); typeof o.stack", .want = "string" },
        .{ .src = "new AggregateError([1,2],'m').errors.length", .want = "2" },
        .{ .src = "try{null.x}catch(e){e instanceof TypeError}", .want = "true" },
        .{ .src = "Object.getPrototypeOf(TypeError)===Error", .want = "true" },
        .{ .src = "try{throw {a:1}}catch(e){e.a}", .want = "1" },
    });
}
