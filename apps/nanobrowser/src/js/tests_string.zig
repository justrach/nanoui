//! String: statics and prototype methods, including UTF-16 behaviour on non-ASCII text.

const t = @import("tests_util.zig");

test "String" {
    try t.expectAll(&.{
        .{ .src = "String(1)+String(null)+String(undefined)+String(true)", .want = "1nullundefinedtrue" },
        .{ .src = "String()", .want = "" },
        .{ .src = "typeof new String('a')", .want = "object" },
        .{ .src = "new String('ab').length", .want = "2" },
        .{ .src = "Object.keys(new String('ab')).join()", .want = "0,1" },
        .{ .src = "String.fromCharCode(97,98)", .want = "ab" },
        .{ .src = "String.fromCharCode(0x20AC)", .want = "\xE2\x82\xAC" },
        .{ .src = "String.fromCharCode(0xD83D,0xDE00).length", .want = "2" },
        .{ .src = "String.fromCodePoint(0x1F600)==='\\u{1F600}'", .want = "true" },
        .{ .src = "try{String.fromCodePoint(-1)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "String.raw`a\\n${1}b`", .want = "a\\n1b" },
        .{ .src = "'abc'.charAt(1)+'abc'.charAt(9)", .want = "b" },
        .{ .src = "'abc'.charCodeAt(1)", .want = "98" },
        .{ .src = "'abc'.charCodeAt(9)", .want = "NaN" },
        .{ .src = "'\\u20AC'.charCodeAt(0)", .want = "8364" },
        .{ .src = "'\\u{1F600}'.charCodeAt(0)", .want = "55357" },
        .{ .src = "'\\u{1F600}'.charCodeAt(1)", .want = "56832" },
        .{ .src = "'\\u{1F600}'.codePointAt(0)", .want = "128512" },
        .{ .src = "'a\\u{1F600}'.codePointAt(2)", .want = "56832" },
        .{ .src = "'abc'.at(-1)", .want = "c" },
        .{ .src = "'a'.concat('b',1)", .want = "ab1" },
        .{ .src = "'abcabc'.indexOf('c')", .want = "2" },
        .{ .src = "'abcabc'.indexOf('c',3)", .want = "5" },
        .{ .src = "'abc'.indexOf('')", .want = "0" },
        .{ .src = "'abc'.indexOf('',9)", .want = "3" },
        .{ .src = "'abcabc'.lastIndexOf('b')", .want = "4" },
        .{ .src = "'abcabc'.lastIndexOf('b',3)", .want = "1" },
        .{ .src = "'\\u20ACb\\u20AC'.indexOf('b')", .want = "1" },
        .{ .src = "'\\u20ACb\\u20AC'.lastIndexOf('\\u20AC')", .want = "2" },
        .{ .src = "'abc'.includes('b')", .want = "true" },
        .{ .src = "'abc'.startsWith('b',1)", .want = "true" },
        .{ .src = "'abc'.endsWith('b',2)", .want = "true" },
        .{ .src = "try{'a'.includes(/a/)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "'abcd'.slice(1,3)+'abcd'.slice(-2)", .want = "bccd" },
        .{ .src = "'abcd'.substring(3,1)", .want = "bc" },
        .{ .src = "'abcd'.substr(1,2)+'abcd'.substr(-1)", .want = "bcd" },
        .{ .src = "'\\u20ACab'.slice(1)", .want = "ab" },
        .{ .src = "'a\\u{1F600}b'.slice(1,3)==='\\u{1F600}'", .want = "true" },
        .{ .src = "'a\\u{1F600}b'.slice(1,2).length", .want = "1" },
        .{ .src = "var h='\\u{1F600}'.slice(0,1),l='\\u{1F600}'.slice(1); (h+l)==='\\u{1F600}'", .want = "true" },
        .{ .src = "'aB'.toUpperCase()+'aB'.toLowerCase()", .want = "ABab" },
        .{ .src = "'\\u00e9'.toUpperCase()==='\\u00c9'", .want = "true" },
        .{ .src = "'\\u00df'.toUpperCase()", .want = "SS" },
        .{ .src = "'\\u03B1'.toUpperCase()==='\\u0391'", .want = "true" },
        .{ .src = "' a '.trim()+'|'+' a '.trimStart()+'|'+' a '.trimEnd()", .want = "a|a | a" },
        .{ .src = "'\\u00a0\\ufeff\\n a'.trim()", .want = "a" },
        .{ .src = "'a'.padStart(3,'xy')+'a'.padEnd(3,'xy')+'a'.padStart(2)", .want = "xyaaxy a" },
        .{ .src = "'ab'.repeat(2)", .want = "abab" },
        .{ .src = "try{'a'.repeat(-1)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "try{'a'.repeat(2**40)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "'a,b'.split(',').join('|')", .want = "a|b" },
        .{ .src = "'abc'.split('').length", .want = "3" },
        .{ .src = "'abc'.split().length", .want = "1" },
        .{ .src = "'a,b,c'.split(',',2).length", .want = "2" },
        .{ .src = "''.split('').length+''.split(',').length", .want = "1" },
        .{ .src = "'a1b2'.split(/\\d/).join()", .want = "a,b," },
        .{ .src = "'a1b'.split(/(\\d)/).join()", .want = "a,1,b" },
        .{ .src = "'abc'.split(/(?:)/).length", .want = "3" },
        .{ .src = "'xax'.replace('x','y')", .want = "yax" },
        .{ .src = "'xax'.replaceAll('x','y')", .want = "yay" },
        .{ .src = "'abc'.replace('b','[$&$`$\\'$$]')", .want = "a[bac$]c" },
        .{ .src = "'abc'.replace('b',m=>m+m)", .want = "abbc" },
        .{ .src = "'aa'.replaceAll('a',(m,i)=>i)", .want = "01" },
        .{ .src = "try{'a'.replaceAll(/a/,'b')}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "'a'.replaceAll('','-')", .want = "-a-" },
        .{ .src = "'abc'.match(/b/)[0]", .want = "b" },
        .{ .src = "'abab'.match(/b/g).length", .want = "2" },
        .{ .src = "'a'.match(/x/)", .want = "null" },
        .{ .src = "[...'a1b2'.matchAll(/\\d/g)].map(m=>m[0]+m.index).join()", .want = "11,23" },
        .{ .src = "'abc'.search(/c/)", .want = "2" },
        .{ .src = "'a'.localeCompare('b')+''+'b'.localeCompare('a')+'a'.localeCompare('a')", .want = "-110" },
        .{ .src = "'a'.localeCompare('B')", .want = "-1" },
        .{ .src = "['b','a','C'].sort((x,y)=>x.localeCompare(y)).join('')", .want = "abC" },
        .{ .src = "'abc'.normalize()", .want = "abc" },
        .{ .src = "try{'a'.normalize('X')}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "'a\\uD800'.isWellFormed()+''+'a'.isWellFormed()", .want = "falsetrue" },
        .{ .src = "'\\uD800'.toWellFormed()==='\\uFFFD'", .want = "true" },
        .{ .src = "[...'a\\u{1F600}'].length", .want = "2" },
        .{ .src = "Object.prototype.toString.call(''[Symbol.iterator]())", .want = "[object String Iterator]" },
        .{ .src = "String.prototype.trim.call(1)", .want = "1" },
        .{ .src = "try{String.prototype.trim.call(null)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "'abc'.toString()+new String('x').valueOf()", .want = "abcx" },
        .{ .src = "'a'<'\\u{1F600}'", .want = "true" },
        .{ .src = "'\\uFFFF'<'\\u{1F600}'", .want = "false" },
        .{ .src = "var s='x';for(var i=0;i<20;i++)s+=s;s.length", .want = "1048576" },
        .{ .src = "var s='';for(var i=0;i<20000;i++)s+='ab';s.charAt(39999)", .want = "b" },
        .{ .src = "var o={};o['a'+'b']=1;o.ab", .want = "1" },
        .{ .src = "var o={};o['1'+'0']=2;o[10]", .want = "2" },
        .{ .src = "encodeURIComponent('a b&c/\\u20AC')", .want = "a%20b%26c%2F%E2%82%AC" },
        .{ .src = "encodeURI('a b&c/')", .want = "a%20b&c/" },
        .{ .src = "decodeURIComponent('a%20b%E2%82%AC')==='a b\\u20AC'", .want = "true" },
        .{ .src = "decodeURI('%26%20')", .want = "%26 " },
        .{ .src = "try{decodeURIComponent('%')}catch(e){e.name}", .want = "URIError" },
        .{ .src = "try{encodeURIComponent('\\uD800')}catch(e){e.name}", .want = "URIError" },
        .{ .src = "escape('a b')+unescape('%41%u0042')", .want = "a%20bAB" },
    });
}
