//! JSON and Date.

const t = @import("tests_util.zig");

test "JSON" {
    try t.expectAll(&.{
        .{ .src = "JSON.stringify({a:1,b:[1,2],c:'x',d:null,e:true})", .want = "{\"a\":1,\"b\":[1,2],\"c\":\"x\",\"d\":null,\"e\":true}" },
        .{ .src = "JSON.stringify({a:undefined,f(){},s:Symbol()})", .want = "{}" },
        .{ .src = "JSON.stringify([undefined,function(){}])", .want = "[null,null]" },
        .{ .src = "JSON.stringify(undefined)", .want = "undefined" },
        .{ .src = "JSON.stringify(function(){})", .want = "undefined" },
        .{ .src = "JSON.stringify(null)", .want = "null" },
        .{ .src = "JSON.stringify('a\"b\\n\\u0001')", .want = "\"a\\\"b\\n\\u0001\"" },
        .{ .src = "JSON.stringify('\\uD800')", .want = "\"\\ud800\"" },
        .{ .src = "JSON.stringify('\\u20AC').length", .want = "3" },
        .{ .src = "JSON.stringify(NaN)+JSON.stringify(Infinity)", .want = "nullnull" },
        .{ .src = "JSON.stringify(-0)", .want = "0" },
        .{ .src = "JSON.stringify(new Number(1))+JSON.stringify(new String('s'))+JSON.stringify(new Boolean(true))", .want = "1\"s\"true" },
        .{ .src = "JSON.stringify({a:1},null,2)", .want = "{\n  \"a\": 1\n}" },
        .{ .src = "JSON.stringify([1,[2]],null,1)", .want = "[\n 1,\n [\n  2\n ]\n]" },
        .{ .src = "JSON.stringify({a:{}},null,'--')", .want = "{\n--\"a\": {}\n}" },
        .{ .src = "JSON.stringify({a:1,b:2},['b'])", .want = "{\"b\":2}" },
        .{ .src = "JSON.stringify({a:1,b:'x'},(k,v)=>typeof v==='number'?v+1:v)", .want = "{\"a\":2,\"b\":\"x\"}" },
        .{ .src = "JSON.stringify({a:1},function(k,v){return k===''?v:undefined})", .want = "{}" },
        .{ .src = "JSON.stringify({toJSON(){return 5}})", .want = "5" },
        .{ .src = "JSON.stringify({d:new Date(0)})", .want = "{\"d\":\"1970-01-01T00:00:00.000Z\"}" },
        .{ .src = "var o={};o.o=o;try{JSON.stringify(o)}catch(e){e.name+e.message}", .want = "TypeErrorConverting circular structure to JSON" },
        .{ .src = "var o={a:{}};JSON.stringify([o.a,o.a])", .want = "[{},{}]" },
        .{ .src = "JSON.stringify(new Map([[1,2]]))", .want = "{}" },
        .{ .src = "JSON.stringify(Object.create({x:1}))", .want = "{}" },
        .{ .src = "JSON.stringify({[Symbol()]:1,2:1,b:1,1:1})", .want = "{\"1\":1,\"2\":1,\"b\":1}" },
        .{ .src = "JSON.parse('{\"a\":[1,2,{\"b\":null}],\"c\":\"x\"}').a[2].b", .want = "null" },
        .{ .src = "JSON.parse(' [1 , 2 ] ').length", .want = "2" },
        .{ .src = "JSON.parse('\"a\\\\n\\\\u0041\"')", .want = "a\nA" },
        .{ .src = "JSON.parse('\"\\\\uD83D\\\\uDE00\"')==='\\u{1F600}'", .want = "true" },
        .{ .src = "JSON.parse('1.5e2')", .want = "150" },
        .{ .src = "JSON.parse('-0')===0", .want = "true" },
        .{ .src = "Object.is(JSON.parse('-0'),-0)", .want = "true" },
        .{ .src = "JSON.parse('true')+''+JSON.parse('null')", .want = "truenull" },
        .{ .src = "try{JSON.parse('{a:1}')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{JSON.parse('[1,]')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{JSON.parse('')}catch(e){e.message}", .want = "Unexpected end of JSON input" },
        .{ .src = "try{JSON.parse('01')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{JSON.parse('1 2')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "try{JSON.parse('\"\\n\"')}catch(e){e.name}", .want = "SyntaxError" },
        .{ .src = "JSON.parse('{\"a\":1,\"b\":2}',(k,v)=>typeof v==='number'?v*2:v).b", .want = "4" },
        .{ .src = "JSON.parse('{\"a\":1,\"b\":2}',(k,v)=>k==='a'?undefined:v).a", .want = "undefined" },
        .{ .src = "JSON.parse('[1,2]',function(k,v){return k==='0'?9:v})[0]", .want = "9" },
        .{ .src = "JSON.parse('{\"__proto__\":1}').__proto__", .want = "1" },
        .{ .src = "JSON.parse('{\"1\":1,\"a\":2}')[1]", .want = "1" },
        .{ .src = "JSON.stringify(JSON.parse('{\"z\":1,\"a\":[true,false]}'))", .want = "{\"z\":1,\"a\":[true,false]}" },
        .{ .src = "Object.prototype.toString.call(JSON)", .want = "[object JSON]" },
        .{ .src = "var d=0,a=[];for(var i=0;i<20000;i++)a=[a]; try{JSON.stringify(a);d=1}catch(e){d=e.name} d===1||d==='RangeError'", .want = "true" },
        .{ .src = "var s='['.repeat(100000); try{JSON.parse(s)}catch(e){e.name==='RangeError'||e.name==='SyntaxError'}", .want = "true" },
    });
}

test "Date" {
    try t.expectAll(&.{
        .{ .src = "new Date(0).toISOString()", .want = "1970-01-01T00:00:00.000Z" },
        .{ .src = "new Date(2020,0,31,12).getMonth()", .want = "0" },
        .{ .src = "new Date(2020,1,29).getDate()", .want = "29" },
        .{ .src = "new Date(2021,1,29).getDate()", .want = "1" },
        .{ .src = "new Date(2020,12,1).getFullYear()", .want = "2021" },
        .{ .src = "new Date(99,0).getFullYear()", .want = "1999" },
        .{ .src = "new Date(2020,0).getDay()", .want = "3" },
        .{ .src = "Date.UTC(2000,0,1)", .want = "946684800000" },
        .{ .src = "Date.UTC(2000)", .want = "946684800000" },
        .{ .src = "new Date(Date.UTC(2000,1,29,1,2,3,4)).toISOString()", .want = "2000-02-29T01:02:03.004Z" },
        .{ .src = "new Date('2000-01-01').getTime()", .want = "946684800000" },
        .{ .src = "new Date('2000-01-01T00:00:00Z').getTime()", .want = "946684800000" },
        .{ .src = "new Date('2000-01-01T00:00:00+01:00').getTime()", .want = "946681200000" },
        .{ .src = "new Date('2000-01-01T00:00:00.5Z').getTime()", .want = "946684800500" },
        .{ .src = "new Date('2000-01').getTime()", .want = "946684800000" },
        .{ .src = "new Date('2000').getTime()", .want = "946684800000" },
        .{ .src = "new Date('+002000-01-01T00:00:00Z').getTime()", .want = "946684800000" },
        .{ .src = "new Date('Sat, 01 Jan 2000 00:00:00 GMT').getTime()", .want = "946684800000" },
        .{ .src = "new Date('1 Jan 2000 00:00:00 +0100').getTime()", .want = "946681200000" },
        .{ .src = "new Date('Jan 1 2000 01:00 PST').getTime()", .want = "946717200000" },
        .{ .src = "new Date('1/2/2000').getDate()", .want = "2" },
        .{ .src = "new Date('Jan 1 2000 1:00 PM').getHours()", .want = "13" },
        .{ .src = "new Date('Tue Mar 01 2022 10:00:00 GMT+0000 (UTC)').getTime()", .want = "1646128800000" },
        .{ .src = "isNaN(new Date('nope').getTime())", .want = "true" },
        .{ .src = "String(new Date(NaN))", .want = "Invalid Date" },
        .{ .src = "try{new Date(NaN).toISOString()}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "new Date(NaN).toJSON()", .want = "null" },
        .{ .src = "new Date(0).toUTCString()", .want = "Thu, 01 Jan 1970 00:00:00 GMT" },
        .{ .src = "new Date(0).toString()", .want = "Thu Jan 01 1970 00:00:00 GMT+0000 (Coordinated Universal Time)" },
        .{ .src = "new Date(0).toDateString()", .want = "Thu Jan 01 1970" },
        .{ .src = "new Date(0).getTimezoneOffset()", .want = "0" },
        .{ .src = "var d=new Date(0); d.setFullYear(2000); d.getFullYear()", .want = "2000" },
        .{ .src = "var d=new Date(0); d.setMonth(13); d.getFullYear()+d.getMonth()", .want = "1972" },
        .{ .src = "var d=new Date(0); d.setDate(32); d.getMonth()+d.getDate()", .want = "2" },
        .{ .src = "var d=new Date(0); d.setHours(25,1,2,3); d.toISOString()", .want = "1970-01-02T01:01:02.003Z" },
        .{ .src = "var d=new Date(0); d.setUTCMinutes(61); d.getUTCHours()", .want = "1" },
        .{ .src = "var d=new Date(0); d.setTime(5); d.getTime()", .want = "5" },
        .{ .src = "var d=new Date(0); d.setMilliseconds(5); +d", .want = "5" },
        .{ .src = "var d=new Date(NaN); d.setFullYear(1970); d.getTime()", .want = "0" },
        .{ .src = "typeof Date.now()", .want = "number" },
        .{ .src = "Date.now()>1600000000000", .want = "true" },
        .{ .src = "typeof Date()", .want = "string" },
        .{ .src = "new Date(new Date(5)).getTime()", .want = "5" },
        .{ .src = "new Date(1)<new Date(2)", .want = "true" },
        .{ .src = "new Date(5)-new Date(2)", .want = "3" },
        .{ .src = "typeof (new Date(0)+1)", .want = "string" },
        .{ .src = "new Date(8.64e15+1).getTime()", .want = "NaN" },
        .{ .src = "new Date(-1).toISOString()", .want = "1969-12-31T23:59:59.999Z" },
        .{ .src = "new Date(Date.UTC(-1,0)).toISOString()", .want = "-000001-01-01T00:00:00.000Z" },
        .{ .src = "new Date(Date.UTC(12345,0)).toISOString()", .want = "+012345-01-01T00:00:00.000Z" },
        .{ .src = "new Date(0)[Symbol.toPrimitive]('number')", .want = "0" },
        .{ .src = "new Date(0).getYear()", .want = "70" },
        .{ .src = "Date.parse('2000-01-01')", .want = "946684800000" },
    });
}
