//! Proxy traps and invariants, Reflect.

const t = @import("tests_util.zig");

test "Proxy" {
    try t.expectAll(&.{
        .{ .src = "var p=new Proxy({},{get:(t,k)=>k+'!'}); p.x", .want = "x!" },
        .{ .src = "var p=new Proxy({a:1},{}); p.a", .want = "1" },
        .{ .src = "var l=[]; var p=new Proxy({},{set(t,k,v){l.push(k,v);t[k]=v;return true}}); p.a=1; l.join()+p.a", .want = "a,11" },
        .{ .src = "var p=new Proxy({},{has:(t,k)=>k=='y'}); ('y' in p)+''+('z' in p)", .want = "truefalse" },
        .{ .src = "var p=new Proxy({a:1},{deleteProperty(t,k){delete t[k];return true}}); delete p.a; 'a' in p", .want = "false" },
        .{ .src = "var p=new Proxy({},{ownKeys:()=>['a','b']}); Reflect.ownKeys(p).join()", .want = "a,b" },
        .{ .src = "var p=new Proxy({},{ownKeys:()=>['a'],getOwnPropertyDescriptor:()=>({value:1,enumerable:true,configurable:true})}); Object.keys(p).join()", .want = "a" },
        .{ .src = "var p=new Proxy({},{ownKeys:()=>['a'],getOwnPropertyDescriptor:()=>({value:1,enumerable:true,configurable:true}),get:()=>7}); var r=[]; for(var k in p) r.push(k); r.join()+p.a", .want = "a7" },
        .{ .src = "var p=new Proxy({},{getOwnPropertyDescriptor:()=>({value:1,configurable:true})}); Object.getOwnPropertyDescriptor(p,'x').value", .want = "1" },
        .{ .src = "var l=0; var p=new Proxy({},{defineProperty(t,k,d){l=d.value;return Reflect.defineProperty(t,k,d)}}); Object.defineProperty(p,'a',{value:5,configurable:true}); l+p.a", .want = "10" },
        .{ .src = "var pr={}; var p=new Proxy({},{getPrototypeOf:()=>pr}); Object.getPrototypeOf(p)===pr", .want = "true" },
        .{ .src = "var pr={}; var p=new Proxy({},{getPrototypeOf:()=>pr}); pr.isPrototypeOf(p)", .want = "true" },
        .{ .src = "var c=0; var p=new Proxy({},{setPrototypeOf(t,v){c=1;return true}}); Object.setPrototypeOf(p,null); c", .want = "1" },
        .{ .src = "var p=new Proxy({},{isExtensible:()=>true}); Object.isExtensible(p)", .want = "true" },
        .{ .src = "var t={}; var p=new Proxy(t,{preventExtensions(tt){Object.preventExtensions(tt);return true}}); Object.preventExtensions(p); Object.isExtensible(t)", .want = "false" },
        .{ .src = "var p=new Proxy(function(){return 1},{apply:(t,th,a)=>a.length+t()}); p(1,2)", .want = "3" },
        .{ .src = "var p=new Proxy(function(){},{construct:(t,a,nt)=>({n:a[0]})}); new p(4).n", .want = "4" },
        .{ .src = "function F(){this.x=1}; var p=new Proxy(F,{}); new p().x", .want = "1" },
        .{ .src = "typeof new Proxy(function(){},{})", .want = "function" },
        .{ .src = "typeof new Proxy({},{})", .want = "object" },
        .{ .src = "try{new Proxy({},{})()}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "try{Proxy({},{})}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "try{new Proxy(1,{})}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var r=Proxy.revocable({},{}); r.revoke(); try{r.proxy.x}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var r=Proxy.revocable({a:1},{}); r.proxy.a", .want = "1" },
        .{ .src = "var t={}; Object.defineProperty(t,'x',{value:1}); var p=new Proxy(t,{get:()=>2}); try{p.x}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var t={}; Object.defineProperty(t,'x',{value:1}); var p=new Proxy(t,{has:()=>false}); try{'x' in p}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var t={}; Object.defineProperty(t,'x',{value:1}); var p=new Proxy(t,{ownKeys:()=>[]}); try{Object.keys(p)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var p=new Proxy({},{ownKeys:()=>['a','a']}); try{Object.keys(p)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var p=new Proxy({},{get:1}); try{p.x}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "'use strict'; var p=new Proxy({},{set:()=>false}); try{p.x=1}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var p=new Proxy({},{get:(t,k,r)=>r===p}); p.x", .want = "true" },
        .{ .src = "var p=new Proxy({},{get:(t,k,r)=>r}); var o=Object.create(p); o.x===o", .want = "true" },
        .{ .src = "var c=0; var p=new Proxy({},{set(t,k,v,r){c=r===o;return true}}); var o=Object.create(p); o.x=1; c", .want = "true" },
        .{ .src = "var p=new Proxy([],{}); p.push(1); p.length", .want = "1" },
        .{ .src = "var p=new Proxy([1,2],{}); [...p].join()+JSON.stringify(p)", .want = "1,2[1,2]" },
        .{ .src = "var p=new Proxy({a:1},{}); JSON.stringify(p)", .want = "{\"a\":1}" },
        .{ .src = "class A{#x=1;g(){return this.#x}}; var p=new Proxy(new A(),{}); try{p.g()}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var p=new Proxy(new Map(),{}); try{p.size}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "Object.prototype.toString.call(new Proxy([],{}))", .want = "[object Array]" },
    });
}

test "Reflect" {
    try t.expectAll(&.{
        .{ .src = "Reflect.get({a:1},'a')", .want = "1" },
        .{ .src = "Reflect.get({get a(){return this}},'a',5)", .want = "5" },
        .{ .src = "var o={}; Reflect.set(o,'a',1)+''+o.a", .want = "true1" },
        .{ .src = "var r={}; Reflect.set({},'a',1,r); r.a", .want = "1" },
        .{ .src = "var o={set a(v){this.b=v}},r={}; Reflect.set(o,'a',1,r); r.b", .want = "1" },
        .{ .src = "Reflect.set(Object.freeze({a:1}),'a',2)", .want = "false" },
        .{ .src = "Reflect.has({a:1},'a')", .want = "true" },
        .{ .src = "Reflect.ownKeys({b:1,[Symbol.iterator]:1,1:1}).length", .want = "3" },
        .{ .src = "Reflect.deleteProperty({a:1},'a')", .want = "true" },
        .{ .src = "Reflect.deleteProperty(Object.freeze({a:1}),'a')", .want = "false" },
        .{ .src = "Reflect.defineProperty({},'a',{value:1})", .want = "true" },
        .{ .src = "Reflect.getOwnPropertyDescriptor({a:1},'a').value", .want = "1" },
        .{ .src = "Reflect.getPrototypeOf([])===Array.prototype", .want = "true" },
        .{ .src = "Reflect.setPrototypeOf({},null)", .want = "true" },
        .{ .src = "Reflect.isExtensible({})", .want = "true" },
        .{ .src = "Reflect.preventExtensions({})", .want = "true" },
        .{ .src = "Reflect.apply(Math.max,null,[1,2])", .want = "2" },
        .{ .src = "Reflect.construct(Date,[0]).getTime()", .want = "0" },
        .{ .src = "class A{}; class B{}; Reflect.construct(A,[],B) instanceof B", .want = "true" },
        .{ .src = "function F(){return new.target}; Reflect.construct(F,[],Map)===Map", .want = "true" },
        .{ .src = "Reflect.construct(Array,[],Map) instanceof Map", .want = "true" },
        .{ .src = "try{Reflect.get(1,'a')}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "Object.prototype.toString.call(Reflect)", .want = "[object Reflect]" },
    });
}
