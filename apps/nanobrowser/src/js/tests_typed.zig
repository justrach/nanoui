//! ArrayBuffer, typed arrays, DataView.

const t = @import("tests_util.zig");

test "typed arrays" {
    try t.expectAll(&.{
        .{ .src = "new ArrayBuffer(8).byteLength", .want = "8" },
        .{ .src = "new ArrayBuffer(8).slice(2,4).byteLength", .want = "2" },
        .{ .src = "ArrayBuffer.isView(new Int8Array(1))+''+ArrayBuffer.isView([])", .want = "truefalse" },
        .{ .src = "new Uint8Array(3).length", .want = "3" },
        .{ .src = "new Uint8Array([1,2,300])[2]", .want = "44" },
        .{ .src = "new Int8Array([200])[0]", .want = "-56" },
        .{ .src = "new Uint8ClampedArray([300,-1,1.5,2.5])[3]", .want = "2" },
        .{ .src = "new Uint8ClampedArray([300,-1,1.5])[2]", .want = "2" },
        .{ .src = "new Int16Array([70000])[0]", .want = "4464" },
        .{ .src = "new Uint16Array([-1])[0]", .want = "65535" },
        .{ .src = "new Int32Array([2**31])[0]", .want = "-2147483648" },
        .{ .src = "new Uint32Array([-1])[0]", .want = "4294967295" },
        .{ .src = "new Float32Array([1.5])[0]", .want = "1.5" },
        .{ .src = "new Float64Array([0.1])[0]", .want = "0.1" },
        .{ .src = "new BigInt64Array([-1n])[0]", .want = "-1" },
        .{ .src = "new BigUint64Array([-1n])[0]", .want = "18446744073709551615" },
        .{ .src = "try{new Int8Array([1n])}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "try{new BigInt64Array([1])}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "var b=new ArrayBuffer(4); new Uint8Array(b)[0]=1; new Uint32Array(b)[0]", .want = "1" },
        .{ .src = "var b=new ArrayBuffer(8); new Uint8Array(b,2,3).length", .want = "3" },
        .{ .src = "var b=new ArrayBuffer(8); new Uint16Array(b,2).byteOffset", .want = "2" },
        .{ .src = "try{new Uint16Array(new ArrayBuffer(8),1)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "try{new Uint8Array(new ArrayBuffer(2),0,3)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "try{Uint8Array(1)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "new Uint8Array(new Set([1,2])).length", .want = "2" },
        .{ .src = "new Uint8Array({length:2,0:5})[0]", .want = "5" },
        .{ .src = "new Uint8Array(new Uint16Array([300]))[0]", .want = "44" },
        .{ .src = "var a=new Uint8Array(1); a[5]=1; a[5]", .want = "undefined" },
        .{ .src = "var a=new Uint8Array(1); a.x=1; a.x", .want = "1" },
        .{ .src = "var a=new Uint8Array(2); 1 in a", .want = "true" },
        .{ .src = "var a=new Uint8Array(2); 2 in a", .want = "false" },
        .{ .src = "Object.keys(new Uint8Array(2)).join()", .want = "0,1" },
        .{ .src = "Uint8Array.BYTES_PER_ELEMENT+new Float64Array(1).BYTES_PER_ELEMENT", .want = "9" },
        .{ .src = "new Float64Array(2).byteLength", .want = "16" },
        .{ .src = "new Int8Array(1).buffer.byteLength", .want = "1" },
        .{ .src = "Object.getPrototypeOf(Int8Array).name", .want = "TypedArray" },
        .{ .src = "Object.prototype.toString.call(new Int8Array(1))", .want = "[object Int8Array]" },
        .{ .src = "try{new (Object.getPrototypeOf(Int8Array))()}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "[...new Uint8Array([1,2])].join()", .want = "1,2" },
        .{ .src = "[...new Uint8Array([1]).entries()][0].join()", .want = "0,1" },
        .{ .src = "new Uint8Array([1,2]).join('-')", .want = "1-2" },
        .{ .src = "new Uint8Array([1,2]).toString()", .want = "1,2" },
        .{ .src = "new Uint8Array([1,2]).map(x=>x*2)[1]", .want = "4" },
        .{ .src = "new Uint8Array([1,2]).map(x=>x) instanceof Uint8Array", .want = "true" },
        .{ .src = "new Uint8Array([1,2]).filter(x=>x>1).length", .want = "1" },
        .{ .src = "new Uint8Array([1,2]).reduce((a,b)=>a+b)", .want = "3" },
        .{ .src = "new Uint8Array([1,2]).reduceRight((a,b)=>a-b)", .want = "1" },
        .{ .src = "var c=0; new Uint8Array([1,2]).forEach(x=>c+=x); c", .want = "3" },
        .{ .src = "new Uint8Array([1,2]).every(x=>x)+''+new Uint8Array([1,2]).some(x=>x>5)", .want = "truefalse" },
        .{ .src = "new Uint8Array([1,2]).find(x=>x>1)+new Uint8Array([1,2]).findIndex(x=>x>1)+new Uint8Array([1,2]).findLast(x=>x)+new Uint8Array([1,2]).findLastIndex(x=>x)", .want = "6" },
        .{ .src = "new Uint8Array([1,2]).includes(2)+''+new Uint8Array([1,2]).indexOf(2)+new Uint8Array([1,2]).lastIndexOf(1)", .want = "true10" },
        .{ .src = "new Uint8Array([1,2]).at(-1)", .want = "2" },
        .{ .src = "new Uint8Array(2).fill(7)[1]", .want = "7" },
        .{ .src = "new Uint8Array([1,2]).reverse()[0]", .want = "2" },
        .{ .src = "var a=new Uint8Array(3); a.set([1,2],1); a.join()", .want = "0,1,2" },
        .{ .src = "try{new Uint8Array(1).set([1,2])}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "new Uint8Array([1,2,3]).slice(1).length", .want = "2" },
        .{ .src = "var a=new Uint8Array([1,2,3]); var s=a.subarray(1); s[0]=9; a[1]", .want = "9" },
        .{ .src = "new Uint8Array([1,2,3,4]).copyWithin(0,2).join()", .want = "3,4,3,4" },
        .{ .src = "new Uint8Array([3,1,2]).sort().join()", .want = "1,2,3" },
        .{ .src = "new Float64Array([10,9,1]).sort().join()", .want = "1,9,10" },
        .{ .src = "new Float64Array([NaN,1,-0,0]).sort().join()", .want = "0,0,1,NaN" },
        .{ .src = "new Uint8Array([3,1]).sort((a,b)=>b-a)[0]", .want = "3" },
        .{ .src = "new BigInt64Array([2n,1n]).sort()[0]", .want = "1" },
        .{ .src = "new Uint8Array([3,1]).toSorted()[0]+new Uint8Array([3,1]).toReversed()[0]", .want = "2" },
        .{ .src = "new Uint8Array([3,1]).with(0,9)[0]", .want = "9" },
        .{ .src = "Uint8Array.from([1,2],x=>x*2)[1]", .want = "4" },
        .{ .src = "Uint8Array.of(1,2).length", .want = "2" },
        .{ .src = "class T extends Uint8Array{}; new T(1) instanceof Uint8Array", .want = "true" },
        .{ .src = "var d=new DataView(new ArrayBuffer(8)); d.setInt16(0,-2); d.getInt16(0)+d.getUint8(0)", .want = "253" },
        .{ .src = "var d=new DataView(new ArrayBuffer(8)); d.setUint32(0,1,true); d.getUint8(0)", .want = "1" },
        .{ .src = "var d=new DataView(new ArrayBuffer(8)); d.setFloat64(0,1.5); d.getFloat64(0)", .want = "1.5" },
        .{ .src = "var d=new DataView(new ArrayBuffer(8)); d.setFloat32(0,1.5,true); d.getFloat32(0,true)", .want = "1.5" },
        .{ .src = "var d=new DataView(new ArrayBuffer(8)); d.setBigInt64(0,-1n); d.getBigUint64(0)", .want = "18446744073709551615" },
        .{ .src = "var d=new DataView(new ArrayBuffer(2),1); d.byteLength+d.byteOffset", .want = "2" },
        .{ .src = "try{new DataView(new ArrayBuffer(1)).getInt16(0)}catch(e){e.name}", .want = "RangeError" },
        .{ .src = "try{new DataView(1)}catch(e){e.name}", .want = "TypeError" },
        .{ .src = "Object.prototype.toString.call(new DataView(new ArrayBuffer(1)))", .want = "[object DataView]" },
    });
}
