const table = blk: {
    const names = @typeInfo(Prop).@"enum".field_names;
    var pairs: [names.len - 1]struct { []const u8, Prop } = undefined;
    @setEvalBranchQuota(200000);
    var n: usize = 0;
    for (names) |name| {
        if (std.mem.eql(u8, name, "custom")) continue;
        var buf: [name.len]u8 = name[0..name.len].*;
        for (&buf) |*c| {
            if (c.* == '_') c.* = '-';
        }
        const final = buf;
        pairs[n] = .{ &final, @field(Prop, name) };
        n += 1;
    }
    const all = pairs;
    break :blk std.StaticStringMap(Prop).initComptime(all);
};

/// The property a lowercase name stands for. A few vendor-prefixed aliases
/// that real stylesheets lean on are honoured.
pub fn lookup(name: []const u8) ?Prop {
