test "a small file of many cheap scans over a frame stops at its allowance" {
    const gpa = testing.allocator;
    var list: std.ArrayList(u8) = .empty;
    defer list.deinit(gpa);
    try list.appendSlice(gpa, &.{ 0xFF, 0xD8 });
    var dqt: [65]u8 = @splat(1);
    dqt[0] = 0;
    try segment(&list, 0xDB, &dqt);
    try segment(&list, 0xC2, &.{ 8, 2, 0, 2, 0, 1, 1, 0x11, 0 });
    // One code: end of band, with a run as long as a run gets.
    var dht: [18]u8 = @splat(0);
    dht[0] = 0x10;
    dht[1] = 1;
    dht[17] = 0xE0;
    try segment(&list, 0xC4, &dht);
    for (0..20000) |_| {
        try segment(&list, 0xDA, &.{ 1, 1, 0, 1, 63, 0x10 });
        try list.appendSlice(gpa, &.{ 0x7F, 0xFF, 0x00 });
    }
    try list.appendSlice(gpa, &.{ 0xFF, 0xD9 });
