fn exifSegment(comptime big: bool, comptime orientation: u8) []const u8 {
    const body = if (big)
        "Exif\x00\x00MM\x00\x2A\x00\x00\x00\x08\x00\x01\x01\x12\x00\x03\x00\x00\x00\x01\x00" ++ [_]u8{orientation} ++ "\x00\x00\x00\x00\x00\x00"
    else
        "Exif\x00\x00II\x2A\x00\x08\x00\x00\x00\x01\x00\x12\x01\x03\x00\x01\x00\x00\x00" ++ [_]u8{orientation} ++ "\x00\x00\x00\x00\x00\x00\x00";
    return "\xFF\xE1\x00" ++ [_]u8{body.len + 2} ++ body;
}

test "EXIF orientation is applied and accounted for in the size" {
    // Left block 50, right block 200.
    const base: Spec = .{ .w = 16, .h = 8, .comps = &.{.{}}, .values = &.{&.{ 50, 200 }} };
    const cases = [_]struct { seg: []const u8, w: u32, h: u32, first: [2]u32 }{
        .{ .seg = exifSegment(true, 1), .w = 16, .h = 8, .first = .{ 0, 0 } },
        .{ .seg = exifSegment(false, 2), .w = 16, .h = 8, .first = .{ 8, 0 } },
        .{ .seg = exifSegment(true, 3), .w = 16, .h = 8, .first = .{ 8, 0 } },
        .{ .seg = exifSegment(false, 4), .w = 16, .h = 8, .first = .{ 0, 0 } },
        .{ .seg = exifSegment(true, 5), .w = 8, .h = 16, .first = .{ 0, 0 } },
        .{ .seg = exifSegment(false, 6), .w = 8, .h = 16, .first = .{ 0, 0 } },
        .{ .seg = exifSegment(true, 7), .w = 8, .h = 16, .first = .{ 0, 8 } },
        .{ .seg = exifSegment(false, 8), .w = 8, .h = 16, .first = .{ 0, 8 } },
    };
    for (cases) |case| {
        var spec = base;
        spec.before = case.seg;
        const bytes = try build(spec);
        defer testing.allocator.free(bytes);
        const s = jpeg.size(bytes).?;
        try testing.expectEqual(case.w, s.width);
        try testing.expectEqual(case.h, s.height);
        const d = try jpeg.decode(testing.allocator, bytes);
        defer d.deinit(testing.allocator);
        try testing.expectEqual(case.w, d.width);
        try testing.expectEqual(case.h, d.height);
        const x = case.first[0];
        const y = case.first[1];
        try expectFlat(d, x, y, x + 8, y + 8, @splat(50));
    }
}

