fn mustNotCrash(bytes: []const u8) void {
    const gpa = testing.allocator;
    _ = jpeg.matches(bytes);
    _ = jpeg.size(bytes);
    const d = jpeg.decode(gpa, bytes) catch return;
    std.debug.assert(d.bgra.len == @as(usize, d.width) * d.height * 4);
    d.deinit(gpa);
}

test "every byte mutated and every truncation: no crash, no leak" {
    const gpa = testing.allocator;
    const made_420 = try build(.{
        .w = 16,
        .h = 16,
        .comps = &.{ .{ .id = 1, .h = 2, .v = 2 }, .{ .id = 2 }, .{ .id = 3 } },
        .values = &.{ &.{ 50, 100, 150, 200 }, &.{90}, &.{200} },
    });
    defer gpa.free(made_420);
    const made_restart = try build(.{ .w = 32, .h = 8, .comps = &.{.{}}, .values = &.{&.{ 10, 20, 30, 40 }}, .restart = 1, .before = exifSegment(false, 6) });
    defer gpa.free(made_restart);
    const made_progressive = try build(.{ .w = 16, .h = 16, .comps = &.{ .{ .id = 1 }, .{ .id = 2 }, .{ .id = 3 }, .{ .id = 4 } }, .values = &.{&.{33}, &.{44}, &.{55}, &.{66}}, .progressive = true });
    defer gpa.free(made_progressive);
    for ([_][]const u8{ &real_sips, &real_progressive, made_420, made_restart, made_progressive }) |file| {
        const copy = try gpa.dupe(u8, file);
        defer gpa.free(copy);
        for (copy, 0..) |*b, i| {
            const was = b.*;
            for ([_]u8{ was ^ 0xFF, was ^ 0x01, was ^ 0x80, 0xFF, 0x00 }) |v| {
                b.* = v;
                mustNotCrash(copy);
            }
            b.* = was;
            mustNotCrash(copy[0..i]);
        }
    }
}

