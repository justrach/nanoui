test "a truncated file decodes as far as it got, unless it got nowhere" {
    const gpa = testing.allocator;
    const bytes = try build(.{ .w = 128, .h = 8, .comps = &.{.{}}, .values = &.{&.{77}} });
    defer gpa.free(bytes);
    const sos = std.mem.indexOf(u8, bytes, &.{ 0xFF, 0xDA }).? + 2 + 8;
    // Half of the coded data.
    const half = try jpeg.decode(gpa, bytes[0 .. sos + (bytes.len - sos) / 2]);
    defer half.deinit(gpa);
    try expectFlat(half, 0, 0, 8, 8, @splat(77));
    try expectFlat(half, 120, 0, 128, 8, @splat(128));
    // Right up to the coded data: a frame header, but no scan data.
    try testing.expectError(error.Corrupt, jpeg.decode(gpa, bytes[0..sos]));
    // Size still reads with the scan gone, and fails with the frame header gone.
    try testing.expectEqual(@as(u32, 128), jpeg.size(bytes[0..sos]).?.width);
    const sof = std.mem.indexOf(u8, bytes, &.{ 0xFF, 0xC0 }).?;
    try testing.expectEqual(@as(?jpeg.Size, null), jpeg.size(bytes[0 .. sof + 4]));
    try testing.expectError(error.Corrupt, jpeg.decode(gpa, bytes[0 .. sof + 4]));
}

