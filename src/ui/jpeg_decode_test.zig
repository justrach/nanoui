/// A red-to-right, green-to-bottom gradient the two real files were made from.
fn expectGradient(d: jpeg.Decoded, tolerance: u8) !void {
    try testing.expectEqual(@as(u32, 16), d.width);
    try testing.expectEqual(@as(u32, 16), d.height);
    for (0..16) |y| {
        for (0..16) |x| {
            const want = [3]u8{ @intCast(x * 16), @intCast(y * 16), 128 };
            try expectNear(d, @intCast(x), @intCast(y), want, tolerance);
        }
    }
}

