const Comp = struct { id: u8 = 1, h: u8 = 1, v: u8 = 1 };

const Spec = struct {
    w: u16,
    h: u16,
    comps: []const Comp,
    /// By component, the sample value of each block in coded order. The last
    /// repeats for as many blocks as the frame still wants.
    values: []const []const u8,
    /// Whole segments to put after SOI.
    before: []const u8 = "",
    restart: u16 = 0,
    quant: u8 = 1,
    quant16: bool = false,
    progressive: bool = false,
};

const Writer = struct {
    list: *std.ArrayList(u8),
    bits: u32 = 0,
    count: u5 = 0,

    fn put(w: *Writer, value: u32, len: u5) !void {
        var i = len;
        while (i > 0) {
            i -= 1;
            w.bits = w.bits << 1 | ((value >> i) & 1);
            w.count += 1;
            if (w.count == 8) try w.byte();
        }
    }

    fn byte(w: *Writer) !void {
        const b: u8 = @truncate(w.bits);
        try w.list.append(testing.allocator, b);
        if (b == 0xFF) try w.list.append(testing.allocator, 0);
        w.bits = 0;
        w.count = 0;
    }

    fn pad(w: *Writer) !void {
        while (w.count != 0) try w.put(1, 1);
    }

    fn huff(w: *Writer, counts: *const [16]u8, values: []const u8, symbol: u8) !void {
        var code: u32 = 0;
        var k: usize = 0;
        for (counts, 1..) |n, len| {
            for (0..n) |_| {
                if (values[k] == symbol) return w.put(code, @intCast(len));
                code += 1;
                k += 1;
            }
            code <<= 1;
        }
        unreachable;
    }

    /// A DC difference: its category's code, then that many bits.
    fn diff(w: *Writer, d: i32) !void {
        const mag: u32 = @abs(d);
        const cat: u5 = @intCast(32 - @clz(mag));
        try w.huff(&dc_counts, &dc_values, cat);
        if (cat > 0) try w.put(if (d < 0) @bitCast(d - 1) else mag, cat);
    }
};

fn segment(list: *std.ArrayList(u8), marker: u8, data: []const u8) !void {
    const gpa = testing.allocator;
    try list.appendSlice(gpa, &.{ 0xFF, marker, @intCast((data.len + 2) >> 8), @truncate(data.len + 2) });
    try list.appendSlice(gpa, data);
}

/// The DC coefficient, by block in coded order, for each component.
fn coefficient(spec: Spec, comp: usize, index: usize) i32 {
    const values = spec.values[comp];
    const v: i32 = values[@min(index, values.len - 1)];
    return @divTrunc((v - 128) * 8, spec.quant);
}

fn build(spec: Spec) ![]u8 {
    const gpa = testing.allocator;
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.appendSlice(gpa, &.{ 0xFF, 0xD8 });
    try out.appendSlice(gpa, spec.before);

    var dqt: [129]u8 = undefined;
    if (spec.quant16) {
        dqt[0] = 0x10;
        for (0..64) |i| {
            dqt[1 + i * 2] = 0;
            dqt[2 + i * 2] = spec.quant;
        }
        try segment(&out, 0xDB, dqt[0..129]);
    } else {
        dqt[0] = 0;
        @memset(dqt[1..65], spec.quant);
        try segment(&out, 0xDB, dqt[0..65]);
    }

    var sof: [18]u8 = undefined;
    sof[0] = 8;
    std.mem.writeInt(u16, sof[1..3], spec.h, .big);
    std.mem.writeInt(u16, sof[3..5], spec.w, .big);
    sof[5] = @intCast(spec.comps.len);
    var hmax: u32 = 1;
    var vmax: u32 = 1;
    for (spec.comps, 0..) |c, i| {
        sof[6 + i * 3] = c.id;
        sof[7 + i * 3] = c.h << 4 | c.v;
        sof[8 + i * 3] = 0;
        hmax = @max(hmax, c.h);
        vmax = @max(vmax, c.v);
    }
    try segment(&out, if (spec.progressive) 0xC2 else 0xC0, sof[0 .. 6 + spec.comps.len * 3]);
    try segment(&out, 0xC4, &([_]u8{0x00} ++ dc_counts ++ dc_values));
    try segment(&out, 0xC4, &([_]u8{0x10} ++ ac_counts ++ ac_values));
    if (spec.restart != 0) try segment(&out, 0xDD, &.{ @intCast(spec.restart >> 8), @truncate(spec.restart) });

    const mcux = (spec.w + 8 * hmax - 1) / (8 * hmax);
    const mcuy = (spec.h + 8 * vmax - 1) / (8 * vmax);
    const passes: []const [2]u8 = if (spec.progressive) &.{ .{ 0, 1 }, .{ 1, 0 } } else &.{.{ 0, 0 }};
    for (passes) |pass| {
        var sos: [12]u8 = undefined;
        sos[0] = @intCast(spec.comps.len);
        for (spec.comps, 0..) |c, i| {
            sos[1 + i * 2] = c.id;
            sos[2 + i * 2] = 0;
        }
        const tail = sos[1 + spec.comps.len * 2..][0..3];
        tail[0] = 0;
        tail[1] = if (spec.progressive) 0 else 63;
        tail[2] = pass[0] << 4 | pass[1];
        try segment(&out, 0xDA, sos[0 .. 4 + spec.comps.len * 2]);

        var w: Writer = .{ .list = &out };
        var preds: [4]i32 = @splat(0);
        var seen: [4]usize = @splat(0);
        var rst: u8 = 0;
        for (0..mcux * mcuy) |mcu| {
            if (spec.restart != 0 and mcu != 0 and mcu % spec.restart == 0) {
                try w.pad();
                try out.appendSlice(gpa, &.{ 0xFF, 0xD0 + rst });
                rst = (rst + 1) & 7;
                preds = @splat(0);
            }
            for (spec.comps, 0..) |c, i| {
                for (0..@as(usize, c.h) * c.v) |_| {
                    const dc = coefficient(spec, i, seen[i]);
                    seen[i] += 1;
                    if (pass[0] == 1) {
                        try w.put(@intCast(dc & 1), 1);
                    } else {
                        const shifted = dc >> @intCast(pass[1]);
                        try w.diff(shifted - preds[i]);
                        preds[i] = shifted;
                        // End of block, in baseline; AC comes in other scans otherwise.
                        if (!spec.progressive) try w.huff(&ac_counts, &ac_values, 0);
                    }
                }
            }
        }
        try w.pad();
    }
    try out.appendSlice(gpa, &.{ 0xFF, 0xD9 });
    return out.toOwnedSlice(gpa);
}

fn decodeSpec(spec: Spec) !jpeg.Decoded {
    const bytes = try build(spec);
    defer testing.allocator.free(bytes);
    return jpeg.decode(testing.allocator, bytes);
}

fn expectNear(d: jpeg.Decoded, x: u32, y: u32, rgb: [3]u8, tolerance: u8) !void {
    const p = d.bgra[(@as(usize, y) * d.width + x) * 4..][0..4];
    try testing.expectEqual(@as(u8, 255), p[3]);
    for ([3]u8{ p[2], p[1], p[0] }, rgb) |got, want| {
        const gap = @abs(@as(i16, got) - want);
        if (gap > tolerance) {
            std.debug.print("pixel {d},{d}: got {any}, want {any}\n", .{ x, y, p[0..3], rgb });
            return error.TestExpectedEqual;
        }
    }
}

fn expectFlat(d: jpeg.Decoded, x0: u32, y0: u32, x1: u32, y1: u32, rgb: [3]u8) !void {
    var y = y0;
    while (y < y1) : (y += 1) {
        var x = x0;
        while (x < x1) : (x += 1) try expectNear(d, x, y, rgb, 1);
    }
}

const rgb_of_ycc = struct {
    fn f(y: f32, cb: f32, cr: f32) [3]u8 {
        return .{ c(y + 1.402 * (cr - 128)), c(y - 0.34414 * (cb - 128) - 0.71414 * (cr - 128)), c(y + 1.772 * (cb - 128)) };
    }
    fn c(v: f32) u8 {
        return @intFromFloat(std.math.clamp(@round(v), 0, 255));
    }
}.f;

