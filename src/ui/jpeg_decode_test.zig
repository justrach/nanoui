test "restart intervals, and a lost interval not shifting what follows it" {
    const spec: Spec = .{ .w = 32, .h = 8, .comps = &.{.{}}, .values = &.{&.{ 10, 20, 30, 40 }}, .restart = 1 };
    const bytes = try build(spec);
    defer testing.allocator.free(bytes);
    const d = try jpeg.decode(testing.allocator, bytes);
    defer d.deinit(testing.allocator);
    for (0..4) |i| try expectFlat(d, @intCast(i * 8), 0, @intCast(i * 8 + 8), 8, @splat(@intCast(10 + i * 10)));

    // Cut out RST0 and the second block: block 3 is still block 3.
    const rst0 = std.mem.indexOf(u8, bytes, &.{ 0xFF, 0xD0 }).?;
    const rst1 = std.mem.indexOf(u8, bytes, &.{ 0xFF, 0xD1 }).?;
    const cut = try std.mem.concat(testing.allocator, u8, &.{ bytes[0..rst0], bytes[rst1..] });
    defer testing.allocator.free(cut);
    const e = try jpeg.decode(testing.allocator, cut);
    defer e.deinit(testing.allocator);
    try expectFlat(e, 0, 0, 8, 8, @splat(10));
    try expectFlat(e, 8, 0, 16, 8, @splat(128));
    try expectFlat(e, 16, 0, 24, 8, @splat(30));
    try expectFlat(e, 24, 0, 32, 8, @splat(40));
}

